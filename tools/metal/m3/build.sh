#!/usr/bin/env bash
# The Metal kernel translator (tools/metal/m3/air2amdgpu.cpp) and what it makes:
#
#   tools/metal/m3/build.sh           translate tools/metal/m3/kernels.metal (Apple's Metal compiler -> AIR -> air2amdgpu) into
#                                     src/mtlkernels.h, the table the fake paravirtual GPU's host falls back to without the helper
#                                     (committed, so building the kext needs neither LLVM nor the Metal toolchain)
#   tools/metal/m3/build.sh helper    the run-time helper for the rig: Build/m3/x86_64/air2amdgpu, x86_64, LLVM and lld linked in
#                                     statically from LLVM_X86 (an LLVM 23 build tree with AMDGPU and lld: see docs/m1-stream.md s.5b)
#
# Here: upstream LLVM 23 and lld from Homebrew (LLVM=/opt/homebrew/opt/llvm, LLD=/opt/homebrew/opt/lld by default) and Xcode's metal.
set -euo pipefail
cd "$(dirname "$0")/../../.."
LLVM=${LLVM:-/opt/homebrew/opt/llvm}
LLD=${LLD:-/opt/homebrew/opt/lld}
B=Build/m3
mkdir -p "$B"

if [ "${1:-}" = helper ]; then
	: "${LLVM_X86:?set LLVM_X86 to the x86_64 LLVM build tree}"
	mkdir -p "$B/x86_64"
	cfg="$LLVM_X86/bin/llvm-config"   # x86_64: runs under Rosetta here
	lld=$(sed -n 's/^LLVM_EXTERNAL_LLD_SOURCE_DIR:[A-Z]*=//p' "$LLVM_X86/CMakeCache.txt")
	libs="amdgpu bitreader irreader passes option lto dtlto debuginfodwarf object"
	# shellcheck disable=SC2046   # llvm-config's flags are meant to split
	clang++ -arch x86_64 -mmacosx-version-min=11.0 -std=c++17 -Os $("$cfg" --cxxflags | sed 's/-arch [^ ]*//g') \
		-I"$lld/include" -I"$LLVM_X86/tools/lld/include" tools/metal/m3/air2amdgpu.cpp \
		-L"$LLVM_X86/lib" -llldELF -llldCommon $("$cfg" --link-static --libs $libs) \
		$("$cfg" --link-static --system-libs $libs) -framework IOKit -o "$B/x86_64/air2amdgpu"
	strip "$B/x86_64/air2amdgpu"
	ls -l "$B/x86_64/air2amdgpu"
	exit 0
fi

# shellcheck disable=SC2046
clang++ -std=c++17 $("$LLVM/bin/llvm-config" --cxxflags) -I"$LLD/include" tools/metal/m3/air2amdgpu.cpp $("$LLVM/bin/llvm-config" --ldflags) -lLLVM \
	-L"$LLD/lib" -llldELF -llldCommon -framework IOKit -Wl,-rpath,"$LLVM/lib" -Wl,-rpath,"$LLD/lib" -o "$B/air2amdgpu"
xcrun -sdk macosx metal -c tools/metal/m3/kernels.metal -o "$B/kernels.air"
: > "$B/table"
for k in $(sed -n 's/^kernel void \([A-Za-z0-9_]*\).*/\1/p' tools/metal/m3/kernels.metal); do
	"$B/air2amdgpu" "$B/kernels.air" "$k" "$B/$k.hsaco" >> "$B/table"
done
python3 - "$B" src/mtlkernels.h <<'PY'
import sys
build, out = sys.argv[1:]
lines = ['//', '//  mtlkernels.h — generated by tools/metal/m3/build.sh from tools/metal/m3/kernels.metal', '//  (metal -c, air2amdgpu).',
         '//  Do not edit; edit the .metal and regenerate.', '//', '', '#pragma once', '#include <stdint.h>', '',
         '// kernargs: a 64-bit address per buffer index 0 .. buffers - 1, u32 threads per threadgroup[3], u32 threads in the grid[3]',
         'struct MtlKernel {', '\tconst char *name;', '\tconst uint8_t *elf;', '\tuint32_t size;', '\tuint32_t buffers;', '\tuint32_t written;   // bit i: buffer index i is written', '};', '']
table = []
for row in open(f'{build}/table'):
    name, buffers, written = row.split()
    data = open(f'{build}/{name}.hsaco', 'rb').read()
    lines.append(f'static const uint8_t kMtl_{name}[] = {{')
    lines += ['\t' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    lines += ['};', '']
    table.append(f'\t{{ "{name}", kMtl_{name}, sizeof(kMtl_{name}), {buffers}, 0x{int(written):x} }},')
    print(f'{name}: {len(data)} bytes, {buffers} buffer(s), written 0x{int(written):x}')
lines += ['static const MtlKernel kMtlKernels[] = {'] + table + ['};', 'static const unsigned kMtlKernelCount = sizeof(kMtlKernels) / sizeof(kMtlKernels[0]);', '']
open(out, 'w').write('\n'.join(lines))
PY
