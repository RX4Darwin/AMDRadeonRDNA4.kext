#!/usr/bin/env bash
# Translate the kernels of tools/metal/m3/kernels.metal (Apple's Metal compiler -> AIR -> air2amdgpu -> gfx1201 code objects) into
# src/mtlkernels.h, the table the fake paravirtual GPU's host runs Metal compute dispatches with. The header is committed, so building
# the kext needs neither LLVM nor the Metal toolchain.
#
#   tools/metal/m3/build.sh            (upstream LLVM 23 with AMDGPU: LLVM=/opt/homebrew/opt/llvm by default; ld.lld on the PATH; Xcode's metal)
set -euo pipefail
cd "$(dirname "$0")/../../.."
LLVM=${LLVM:-/opt/homebrew/opt/llvm}
B=Build/m3
mkdir -p "$B"
# shellcheck disable=SC2046   # llvm-config's flags are meant to split
clang++ -std=c++17 $("$LLVM/bin/llvm-config" --cxxflags) tools/metal/m3/air2amdgpu.cpp $("$LLVM/bin/llvm-config" --ldflags) -lLLVM \
	-Wl,-rpath,"$LLVM/lib" -o "$B/air2amdgpu"
xcrun -sdk macosx metal -c tools/metal/m3/kernels.metal -o "$B/kernels.air"
: > "$B/table"
for k in $(sed -n 's/^kernel void \([A-Za-z0-9_]*\).*/\1/p' tools/metal/m3/kernels.metal); do
	"$B/air2amdgpu" "$B/kernels.air" "$k" "$B/$k.o" >> "$B/table"
	ld.lld -shared "$B/$k.o" -o "$B/$k.hsaco"
done
python3 - "$B" src/mtlkernels.h <<'PY'
import sys
build, out = sys.argv[1:]
lines = ['//', '//  mtlkernels.h — generated by tools/metal/m3/build.sh from tools/metal/m3/kernels.metal', '//  (metal -c, air2amdgpu, ld.lld -shared).',
         '//  Do not edit; edit the .metal and regenerate.', '//', '', '#pragma once', '#include <stdint.h>', '',
         '// kernargs: a 64-bit address per buffer index 0 .. buffers - 1, u32 threads per threadgroup[3], u32 threads in the grid[3]',
         'struct MtlKernel {', '\tconst char *name;', '\tconst uint8_t *elf;', '\tuint32_t size;', '\tuint32_t buffers;', '\tuint32_t written;   // bit i: buffer index i is written', '};', '']
table = []
for row in open(f'{build}/table'):
    name, buffers, written = row.split()
    data = open(f'{build}/{name}.hsaco', 'rb').read()
    lines.append(f'static const uint8_t kMtl_{name}[] = {{')
    lines += ['\t' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',' for i in range(0, len(data), 16)]
    lines += ['};', '']
    table.append(f'\t{{ "{name}", kMtl_{name}, sizeof(kMtl_{name}), {buffers}, 0x{int(written):x} }},')
    print(f'{name}: {len(data)} bytes, {buffers} buffer(s), written 0x{int(written):x}')
lines += ['static const MtlKernel kMtlKernels[] = {'] + table + ['};', 'static const unsigned kMtlKernelCount = sizeof(kMtlKernels) / sizeof(kMtlKernels[0]);', '']
open(out, 'w').write('\n'.join(lines))
PY
