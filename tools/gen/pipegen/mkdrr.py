#!/usr/bin/env python3
"""mkdrr.py <linux commit> <pipegen drr trace for pipe 0> ... > src/drr_linux.inc

Variable refresh as amdgpu programs it (pipegen's "drr" scenario): for each pipe, the writes that make its refresh
variable ("on"), fixed again ("off"), and the trigger after each flip. The scenario's V totals 0x2001/0x3001 are
written as 0x2000/0x3000 (the registers take total - 1): those steps get kVMin/kVMax, and the driver puts in the
mode's own (src/drr.cpp). Waits, delays and marks are dropped."""
import sys

def phases(path):
    out, cur = {}, None
    for l in open(path):
        p = l.split()
        if not p:
            continue
        if p[0] == 'MARK':
            cur = p[1].split(':')[1] if p[1].startswith('begin:') else None
            if cur:
                out[cur] = []
        elif p[0] in ('W', 'U') and cur:
            seg, reg, mask, value = int(p[1]), int(p[2], 16), int(p[3], 16), int(p[4], 16)
            kind = {0x2000: 'kVMin', 0x3000: 'kVMax'}.get(value, 'kPlain')
            assert kind == 'kPlain' or 'set_vtotal' in p[-1], l
            out[cur].append((seg, reg, mask, value, kind, p[-1]))
    return out

print(f'''// GENERATED by tools/gen/pipegen (run.sh drr) from Linux {sys.argv[1][:12]}. Do not edit.
// Variable refresh as amdgpu programs it on DCN 4.01 (dcn10_set_drr, optc401_set_drr, optc2_program_manual_trigger),
// for pipes 0-3: on, off, and the trigger after a flip. {{ segment, dword, mask, value, kind }}: reg = (reg & ~mask) |
// value, where kVMin and kVMax steps take the minimum and maximum V total - 1 instead.''')
for pipe, path in enumerate(sys.argv[2:]):
    ph = phases(path)
    for name in ('on', 'off', 'trigger'):
        steps = ph[name]
        assert steps, (path, name)
        print(f'static const Drr::Step kPipe{pipe}{name.capitalize()}[] = {{')
        for seg, reg, mask, value, kind, fn in steps:
            print(f'\t{{ {seg}, 0x{reg:04x}, 0x{mask:08x}, 0x{value:08x}, Drr::{kind} }},   // {fn}')
        print('};')
        sys.stderr.write(f'mkdrr: pipe {pipe} {name}: {len(steps)} writes\n')
