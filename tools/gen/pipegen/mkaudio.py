#!/usr/bin/env python3
"""mkaudio.py <linux commit> <pipegen audio trace for DIG0> ... > src/audio_linux.inc

Audio on a lit DisplayPort stream as amdgpu programs it (pipegen's "audio" scenario, docs/audio-plan.md): the one-time
setup (dce_aud_hw_init, only run for endpoint 0, from DIG0's trace) and one table per stream encoder DIG0-3 with its
Azalia endpoint, every write and update in order (the scenario has no waits). The traces carry the Samsung's audio in
the endpoint's sink description; the kext puts in the monitor's own (Audio::sinkValue), at the writes to the endpoint's
data register (its index register + 1) after the index register names a sink register."""
import sys

def steps(path):
    out, phase = [], None
    for l in open(path):
        p = l.split()
        if not p:
            continue
        if p[0] == 'MARK':
            phase = p[1]
        elif p[0] in ('W', 'U'):
            out.append((int(p[1]), int(p[2], 16), int(p[3], 16), int(p[4], 16), p[-1], phase))
        elif p[0] in ('WAIT', 'DELAY', 'COPY'):
            sys.exit(f'mkaudio: unexpected {p[0]} in {path}: {l.strip()}')
    return out

def table(name, rows):
    print(f'static const Step {name}[] = {{')
    for seg, reg, mask, value, fn, ph in rows:
        print(f'\t{{ {seg}, 0x{reg:04x}, 0x{mask:08x}, 0x{value:08x} }},   // {ph}: {fn}')
    print('};')

print(f'''// GENERATED by tools/gen/pipegen (run.sh audio, mkaudio.py) from Linux {sys.argv[1][:12]}. Do not edit.
// Audio on a lit DisplayPort stream as amdgpu programs it on DCN 4.01: dce_aud_hw_init once (kInit), then for each
// stream encoder DIG0-3 and its Azalia endpoint dp_audio_setup + dce_aud_az_configure, dce_aud_wall_dto_setup,
// dce110_enable_audio_stream. {{ segment, dword, mask, value }}: reg = (reg & ~mask) | value. The endpoint's sink
// description is the rig's Samsung's (Odyssey G70D: LPCM 2 channels, 32-48 kHz); Audio::sinkValue puts in the monitor's.''')
traces = [steps(p) for p in sys.argv[2:]]
table('kInit', [s for s in traces[0] if s[5] == 'begin:init'])
index = []
for dig, t in enumerate(traces):
    rows = [s for s in t if s[5] != 'begin:init']
    assert not any(s[5] == 'begin:init' for s in t[1:]) or dig == 0, dig
    idx = [s[1] for s in rows if s[4] in ('write_indirect_azalia_reg', 'read_indirect_azalia_reg') and s[2] == 0xffffffff and s[0] == 2]
    index.append(min(idx))   # the index register; its data register is the next one
    table(f'kDig{dig}', rows)
    sys.stderr.write(f'mkaudio: DIG{dig}: {len(rows)} steps, endpoint index register 0x{index[-1]:04x}\n')
print('static const Step *const kDigSteps[4] = { kDig0, kDig1, kDig2, kDig3 };')
print('static const size_t kDigCount[4] = { sizeof(kDig0) / sizeof(kDig0[0]), sizeof(kDig1) / sizeof(kDig1[0]),')
print('                                     sizeof(kDig2) / sizeof(kDig2[0]), sizeof(kDig3) / sizeof(kDig3[0]) };')
print('static const size_t kInitCount = sizeof(kInit) / sizeof(kInit[0]);')
print(f'static const uint32_t kEndpointIndex[4] = {{ ' + ', '.join(f'0x{i:04x}' for i in index) + ' };   // segment 2')
