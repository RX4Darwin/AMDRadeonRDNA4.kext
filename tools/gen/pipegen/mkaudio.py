#!/usr/bin/env python3
"""mkaudio.py <linux commit> <pipegen audio trace> > src/audio_linux.inc

Audio on the lit DisplayPort boot display as amdgpu programs it (pipegen's "audio" scenario, docs/audio-plan.md):
every write and update in order, waits dropped (the scenario has none). The sink's audio is in the values (the Azalia
endpoint's sink description), so the table is the rig's Samsung's only."""
import sys

steps, phase = [], None
for l in open(sys.argv[2]):
    p = l.split()
    if not p:
        continue
    if p[0] == 'MARK':
        phase = p[1]
    elif p[0] in ('W', 'U'):
        seg, reg, mask, value = int(p[1]), int(p[2], 16), int(p[3], 16), int(p[4], 16)
        steps.append((seg, reg, mask, value, p[-1], phase))
    elif p[0] in ('WAIT', 'DELAY', 'COPY'):
        sys.exit(f'mkaudio: unexpected {p[0]} in the trace: {l.strip()}')
print(f'''// GENERATED by tools/gen/pipegen (run.sh audio, mkaudio.py) from Linux {sys.argv[1][:12]}. Do not edit.
// Audio on the lit DisplayPort boot display (pipe 0, DIG0, Azalia endpoint 0) as amdgpu programs it on DCN 4.01:
// dce_aud_hw_init, dp_audio_setup + dce_aud_az_configure, dce_aud_wall_dto_setup, dce110_enable_audio_stream, for the
// rig's Samsung (Odyssey G70D: LPCM 2 channels, 32-48 kHz). {{ segment, dword, mask, value }}: reg = (reg & ~mask) | value.''')
print('static const Audio::Step kBootDpAudio[] = {')
for seg, reg, mask, value, fn, phase in steps:
    print(f'\t{{ {seg}, 0x{reg:04x}, 0x{mask:08x}, 0x{value:08x} }},   // {phase}: {fn}')
print('};')
sys.stderr.write(f'mkaudio: {len(steps)} steps\n')
