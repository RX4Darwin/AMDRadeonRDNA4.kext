#!/usr/bin/env python3
# Write src/amdgpu/dsc_qp444.h, the RGB / YCbCr 4:4:4 tables of Linux's qp_tables.h with bits per pixel in sixteenths:
#   tools/gen/pipegen/mkqp.py lib/linux > src/amdgpu/dsc_qp444.h
import re, subprocess, sys

L = sys.argv[1]
src = open(f"{L}/drivers/gpu/drm/amd/display/dc/dml/dsc/qp_tables.h").read()
rev = subprocess.run(["git", "-C", L, "rev-parse", "--short=12", "HEAD"], capture_output=True, text=True).stdout.strip()
licence = re.search(r"/\*\n( \* Copyright.*?)\n \*/", src, re.S).group(1)

print("/*\n * src/amdgpu/dsc_qp444.h: the RGB / YCbCr 4:4:4 tables of Linux's qp_tables.h (drivers/gpu/drm/amd/display/dc/dml/dsc,")
print(f" * Linux {rev}), generated by tools/gen/pipegen/mkqp.py: bits per pixel in sixteenths instead of float. Do not edit.\n *")
print(licence + "\n */")
print("#pragma once\n#include <stdint.h>\n\nnamespace Dsc {\nstruct QpRow { uint16_t bpp16; int8_t qp[15]; };")
for bpc in (8, 10, 12):
    for kind in ("min", "max"):
        body = re.search(rf"qp_table_444_{bpc}bpc_{kind} = \{{(.*?)\n\}};", src, re.S).group(1)
        print(f"\nstatic const QpRow kQp444_{bpc}_{kind}[] = {{")
        for bpp, qp in re.findall(r"\{\s*([\d.]+),\s*\{([^}]*)\}\s*\}", body):
            vals = ", ".join(v.strip() for v in qp.split(","))
            print(f"\t{{ {round(float(bpp) * 16):3d}, {{ {vals} }} }},")
        print("};")
print("}  // namespace Dsc")
