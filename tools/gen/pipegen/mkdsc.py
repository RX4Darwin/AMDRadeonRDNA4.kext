#!/usr/bin/env python3
# mkdsc.py <linux commit> <lanes:rate:trace>...: test/ref/dsc_regs_linux.inc from pipegen's "dsc" traces (run.sh): per timing, the
# DSC engine's registers as dsc_write_to_registers writes them before link training, the OPTC's bytes per pixel and
# slice width (optc2_set_dsc_config) and the PPS's four secondary-data packets (vpg3_update_generic_info_packet).
import sys

def parse(path):
    cfg, engine, optc_bpp, slice_w, pps = None, [], None, None, []
    for line in open(path):
        f = line.split()
        if not f:
            continue
        if f[0] == 'CONFIG':
            cfg = [int(x) for x in f[1:17]]
        label = line.split(';', 1)[1].strip() if ';' in line else ''
        if f[0] == 'W' and label == 'dsc_write_to_registers' and len(engine) < 28:
            engine.append(int(f[4], 16))
        elif label == 'optc2_set_dsc_config' and optc_bpp is None and f[0] == 'W':
            optc_bpp = int(f[4], 16)
        elif label == 'optc2_set_dsc_config' and slice_w is None and f[0] == 'U' and int(f[3], 16) == 0x1fff0000:
            slice_w = int(f[4], 16) >> 16
        elif f[0] == 'W' and label == 'vpg3_update_generic_info_packet' and len(pps) < 36:
            pps.append(int(f[4], 16))
    if not cfg or len(engine) != 28 or optc_bpp is None or slice_w is None or len(pps) != 36:
        sys.exit(f'mkdsc: {path}: incomplete trace ({len(engine)} engine writes, {len(pps)} packet dwords)')
    return cfg, engine, optc_bpp, slice_w, pps

print(f'// Generated by tools/gen/pipegen/run.sh (mkdsc.py) from Linux {sys.argv[1]}: DCN 4.01 DSC for a DP SST RGB 8 bpc')
print('// stream (pipegen dplink d 0 0 dsc) on the link given (lanes, LINK_BW_SET): the engine registers, OPTC bytes per')
print('// pixel and slice width, PPS packets.')
print('// Do not edit.')
print('static const DscRegRef kDscRegRef[] = {')
for run in sys.argv[2:]:
    lanes, rate, path = run.split(':', 2)
    cfg, engine, bpp, sw, pps = parse(path)
    h = cfg[4:8]; v = cfg[8:12]; khz = cfg[12]
    print(f'\t{{ {h[0]}, {h[1]}, {h[2]}, {h[3]}, {v[0]}, {v[1]}, {v[2]}, {v[3]}, {khz}, {lanes}, 0x{int(rate):02x},')
    print('\t  { ' + ', '.join(f'0x{x:08x}' for x in engine) + ' },')
    print(f'\t  0x{bpp:08x}, {sw},')
    print('\t  { ' + ', '.join('{ ' + ', '.join(f'0x{x:08x}' for x in pps[9 * k:9 * k + 9]) + ' }' for k in range(4)) + ' } },')
print('};')
