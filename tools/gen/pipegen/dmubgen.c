/* dmubgen: run Linux's DMUB service (dmub/src, DCN 4.01) on the host against recording register callbacks and
 * print, as a C include, what amdgpu does to start the display microcontroller with a firmware the PSP has
 * loaded: the windows dmub_srv_calc_region_info lays out for this firmware (amdgpu_dm_dmub.c dm_dmub_sw_init),
 * then the register reads and writes of dmub_srv_hw_reset, dmub_srv_hw_init and dmub_srv_wait_for_auto_load
 * (dm_dmub_hw_init with the PSP's load: no backdoor load of the instructions). Built and run by dmubgen.sh. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "dmub/dmub_srv.h"
#include "dmub/src/dmub_dcn401.h"

/* amdgpu_ucode.h's common_firmware_header and dmcub_firmware_header_v1_0 (little-endian, as the host is) */
struct dmcub_header {
	uint32_t size_bytes, header_size_bytes;
	uint16_t header_version_major, header_version_minor, ip_version_major, ip_version_minor;
	uint32_t ucode_version, ucode_size_bytes, ucode_array_offset_bytes, crc32;
	uint32_t inst_const_bytes, bss_data_bytes;
};

/* The windows' framebuffer address: a sentinel the steps carry (the driver puts its own there). */
#define FB_SENTINEL 0x00f0000000000000ull

static struct { uint32_t addr, val; } regs[512];
static int nregs;

static uint32_t peek(uint32_t a)
{
	for (int i = 0; i < nregs; i++)
		if (regs[i].addr == a)
			return regs[i].val;
	return 0;
}

static void poke(uint32_t a, uint32_t v)
{
	for (int i = 0; i < nregs; i++)
		if (regs[i].addr == a) {
			regs[i].val = v;
			return;
		}
	regs[nregs].addr = a;
	regs[nregs++].val = v;
}

static const struct dmub_srv_dcn401_regs *R;

/* The model: what was written reads back, except that the controller always reads enabled and out of its wait
 * (a firmware is running), STOP_FW is answered at once, and the firmware reports itself up (dal_fw, mailbox_rdy). */
static uint32_t rd(void *ctx, uint32_t a)
{
	uint32_t v = peek(a);

	if (a == R->offset.DMCUB_SCRATCH7)
		v = DMUB_GPINT__STOP_FW_RESPONSE;
	if (a == R->offset.DMCUB_CNTL)
		v |= R->mask.DMCUB_CNTL__DMCUB_ENABLE | R->mask.DMCUB_CNTL__DMCUB_PWAIT_MODE_STATUS;
	if (a == R->offset.DMCUB_SCRATCH0)
		v = 0x3;
	printf("\t{ 'R', 0x%05x, 0x%08x },\n", a, v);
	return v;
}

static void wr(void *ctx, uint32_t a, uint32_t v)
{
	poke(a, v);
	printf("\t{ 'W', 0x%05x, 0x%08x },\n", a, v);
}

int main(int argc, char **argv)
{
	static struct dmub_srv dmub;
	struct dmub_srv_create_params cp = { 0 };
	struct dmub_srv_fw_meta_info_params mp = { 0 };
	struct dmub_srv_region_params rp = { 0 };
	struct dmub_srv_region_info ri = { 0 };
	struct dmub_srv_memory_params mem = { 0 };
	static struct dmub_srv_fb_info fb;
	struct dmub_srv_hw_params hp = { 0 };
	struct dmub_fw_meta_info meta;
	static enum dmub_window_memory_type types[DMUB_WINDOW_TOTAL];   /* all FB (0), as dm_dmub_sw_init has them */
	static uint8_t fw[1 << 21], cpu[1 << 24];
	FILE *f;
	size_t n;

	if (argc != 4 || !(f = fopen(argv[1], "rb"))) {
		fprintf(stderr, "usage: dmubgen <dcn_4_0_1_dmcub.bin> <vbios bytes> <linux commit>\n");
		return 2;
	}
	n = fread(fw, 1, sizeof(fw), f);
	fclose(f);

	const struct dmcub_header *hdr = (const void *)fw;
	const uint32_t array = hdr->ucode_array_offset_bytes;

	cp.funcs.reg_read = rd;
	cp.funcs.reg_write = wr;
	cp.asic = DMUB_ASIC_DCN401;
	if (dmub_srv_create(&dmub, &cp) != DMUB_STATUS_OK) {
		fprintf(stderr, "dmub_srv_create failed\n");
		return 1;
	}
	R = dmub.regs_dcn401;

	mp.inst_const_size = hdr->inst_const_bytes - PSP_HEADER_BYTES_256;
	mp.bss_data_size = hdr->bss_data_bytes;
	mp.fw_inst_const = fw + array + PSP_HEADER_BYTES_256;
	mp.fw_bss_data = mp.bss_data_size ? fw + array + hdr->inst_const_bytes : NULL;
	const bool have_meta = dmub_srv_get_fw_meta_info_from_raw_fw(&mp, &meta) == DMUB_STATUS_OK;

	rp.inst_const_size = mp.inst_const_size;
	rp.bss_data_size = mp.bss_data_size;
	rp.vbios_size = strtoul(argv[2], NULL, 0);
	rp.fw_inst_const = mp.fw_inst_const;
	rp.fw_bss_data = mp.fw_bss_data;
	rp.window_memory_type = types;
	rp.fw_info = have_meta ? &meta : NULL;
	if (dmub_srv_calc_region_info(&dmub, &rp, &ri) != DMUB_STATUS_OK) {
		fprintf(stderr, "calc_region_info failed\n");
		return 1;
	}
	mem.region_info = &ri;
	mem.cpu_fb_addr = cpu;
	mem.gpu_fb_addr = FB_SENTINEL;
	mem.window_memory_type = types;
	if (ri.fb_size > sizeof(cpu) || dmub_srv_calc_mem_info(&dmub, &mem, &fb) != DMUB_STATUS_OK) {
		fprintf(stderr, "calc_mem_info failed (fb %u bytes)\n", ri.fb_size);
		return 1;
	}

	printf("// GENERATED by tools/gen/pipegen/dmubgen.sh from Linux %s (drivers/gpu/drm/amd/display/dmub) and\n"
	       "// dcn_4_0_1_dmcub.bin (%zu bytes, version 0x%08x, meta info %s), with a %u-byte VBIOS. Do not edit.\n//\n"
	       "// How amdgpu starts the display microcontroller once the PSP has loaded its firmware: dm_dmub_sw_init's\n"
	       "// windows (offset and size in its framebuffer, all in VRAM), then dmub_srv_hw_reset, dmub_srv_hw_init (no\n"
	       "// backdoor load) and dmub_srv_wait_for_auto_load, as the register reads and writes they made against a\n"
	       "// model (a running firmware that stops at once and comes up at once). Registers are DCN dword offsets; the\n"
	       "// framebuffer is at kDmubLinuxFb. test/dmubload-test.cpp holds src/dmubload.cpp against it.\n\n",
	       argv[3], n, hdr->ucode_version, have_meta ? "found" : "none", rp.vbios_size);
	printf("static const uint32_t kDmubLinuxFwVersion = 0x%08x, kDmubLinuxFbSize = 0x%x;\n", hdr->ucode_version, ri.fb_size);
	printf("static const uint64_t kDmubLinuxFb = 0x%016llxull;\n", (unsigned long long)FB_SENTINEL);
	printf("static const struct { uint32_t offset, size; } kDmubLinuxWindows[%d] = {\n", fb.num_fb);
	for (int i = 0; i < fb.num_fb; i++)
		printf("\t{ 0x%06llx, 0x%06x },\n", (unsigned long long)(fb.fb[i].gpu_addr - FB_SENTINEL), fb.fb[i].size);
	printf("};\n\n// 'M' 0: dmub_srv_hw_reset, 1: dmub_srv_hw_init, 2: dmub_srv_wait_for_auto_load\n");
	printf("static const struct { char op; uint32_t reg, value; } kDmubLinuxSteps[] = {\n");

	printf("\t{ 'M', 0, 0 },\n");
	dmub_srv_hw_reset(&dmub);
	hp.fb_info = &fb;
	printf("\t{ 'M', 1, 0 },\n");
	if (dmub_srv_hw_init(&dmub, &hp) != DMUB_STATUS_OK) {
		fprintf(stderr, "hw_init failed\n");
		return 1;
	}
	printf("\t{ 'M', 2, 0 },\n");
	if (dmub_srv_wait_for_auto_load(&dmub, 100000) != DMUB_STATUS_OK) {
		fprintf(stderr, "auto load wait failed\n");
		return 1;
	}
	printf("};\n");
	return 0;
}
