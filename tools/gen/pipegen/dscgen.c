/*
 * dscgen.c: run Linux's DSC policy and PPS code (dc_dsc.c, dcn20_dsc.c, dcn401_dsc.c, rc_calc*.c, drm_dsc_helper.c) on the
 * host for a matrix of sinks, timings, links and clocks, and print test/ref/dsc_linux.inc, which test/dsc-test.cpp holds
 * src/dsc.cpp against. Built by dscgen.sh.
 *
 * Each case is what amdgpu does for a DP SST stream: dc_dsc_parse_dsc_dpcd on the sink's DPCD 0x060-0x06F,
 * dc_dsc_compute_config with the default options against the link's bandwidth (dp_link_bandwidth_kbps, 8b/10b with FEC),
 * then the PPS SDP of link_dpms.c (dsc_config with the full picture, no padding) through dsc2_get_packed_pps, and
 * dsc_prepare_config for what the OPTC and the encoder take beside it.
 */
#include "dm_services.h"
#include "dc.h"
#include "clk_mgr.h"
#include "core_types.h"
#include "resource.h"
#include "link_service_types.h"
#include "dsc.h"
#include "dcn20/dcn20_dsc.h"
#include "dcn401/dcn401_dsc.h"

static unsigned g_dscclk, g_dispclk;
static unsigned max_clock(struct clk_mgr *c, enum clk_type t) { return t == CLK_TYPE_DSCCLK ? g_dscclk : g_dispclk; }

static struct clk_mgr_funcs g_clk_funcs = { .get_max_clock_khz = max_clock };
static struct clk_mgr g_clk = { .funcs = &g_clk_funcs };
static struct resource_caps g_res_cap = { .num_dsc = 4 };
static struct resource_pool g_pool = { .res_cap = &g_res_cap };
static struct dc g_dc;
static struct dc_context g_ctx;

/* DPCD 0x060-0x06F of the sinks tried (DSC_SUPPORT .. DSC_BRANCH_*): see test/dsc-test.cpp for what each is */
static const uint8_t kSinks[][16] = {
	/* DSC 1.2, 6 KiB RC buffer, 1/2/4/8 slices, 9-bit line buffer, block prediction, RGB/444/simple 422, 8/10 bpc,
	 * 340 MP/s, slices up to 2560 wide, 1/16 bpp steps */
	{ 0x01, 0x21, 0x00, 0x05, 0x2b, 0x00, 0x01, 0x00, 0x00, 0x07, 0x06, 0x11, 0x08, 0x00, 0x00, 0x00 },
	/* DSC 1.1, 8 KiB, 1/2/4 slices, 8-bit line buffer, no block prediction, RGB, 8 bpc, 400 MP/s, 2560 wide, whole bpp */
	{ 0x01, 0x11, 0x00, 0x07, 0x0b, 0x08, 0x00, 0x00, 0x00, 0x01, 0x02, 0x22, 0x08, 0x00, 0x00, 0x04 },
	/* DSC 1.2, 6 KiB, 1-12 and 16 slices, 11-bit line buffer, block prediction, RGB/444, 8/10/12 bpc, 1000 MP/s, 5120 wide,
	 * 1/4 bpp steps */
	{ 0x01, 0x21, 0x00, 0x05, 0xfb, 0x02, 0x01, 0x00, 0x00, 0x03, 0x0e, 0xee, 0x10, 0x01, 0x00, 0x02 },
};

/* DPCD 0x0A0-0x0A2, a sink that is no branch device: amdgpu_dm_connector.c passes them as read (zeros), and only with
 * them does dc_dsc_parse_dsc_dpcd mark the sink DP, which counts the DSC stream overhead */
static const uint8_t kNoBranch[3];

struct tim { unsigned ha, va, ht, vt, khz; };
static const struct tim kTimings[] = {
	{ 3840, 2160, 4400, 2250,  594000 },   /* 60 Hz, CTA */
	{ 3840, 2160, 4000, 2222,  533250 },   /* 60 Hz, CVT-RB */
	{ 3840, 2160, 4400, 2250, 1188000 },   /* 120 Hz, CTA (the Samsung's EDID) */
	{ 3840, 2160, 4000, 2222, 1066500 },   /* 120 Hz, CVT-RB */
	{ 3840, 2160, 4000, 2222, 1279800 },   /* 144 Hz, CVT-RB */
	{ 3840, 2160, 3920, 2287, 1290980 },   /* 144 Hz, CVT-RB2 */
	{ 3840, 2160, 4000, 2222, 2133000 },   /* 240 Hz */
	{ 2560, 1440, 2720, 1525,  995520 },   /* 240 Hz */
	{ 5120, 1440, 5280, 1500, 1900800 },   /* 240 Hz, super-wide */
	{ 5120, 2880, 5280, 2962, 1876000 },   /* 120 Hz, 5K */
	{ 7680, 4320, 7760, 4381, 2039840 },   /* 60 Hz, 8K */
	{ 1920, 1080, 2200, 1125,  148500 },   /* fits uncompressed: no DSC */
};
static const unsigned kBpc[] = { 8, 10, 12 };
static const struct { unsigned lanes, rate; } kLinks[] = { { 4, 0x14 }, { 4, 0x1e }, { 2, 0x1e }, { 4, 0x0a } };
static const struct { unsigned dscclk, dispclk; } kClocks[] = { { 600000, 1800000 }, { 400000, 1200000 } };

static enum dc_color_depth depth(unsigned bpc) {
	return bpc == 8 ? COLOR_DEPTH_888 : bpc == 10 ? COLOR_DEPTH_101010 : COLOR_DEPTH_121212;
}

/* dp_link_bandwidth_kbps (link_validation.c), 8b/10b with FEC: a dc_link is not built here */
static uint32_t link_kbps(unsigned lanes, unsigned rate) {
	uint32_t eff = DATA_EFFICIENCY_8b_10b_x10000 / 100 * DATA_EFFICIENCY_8b_10b_FEC_EFFICIENCY_x100;
	return rate * LINK_RATE_REF_FREQ_IN_KHZ * BITS_PER_DP_BYTE * lanes / 10000 * eff;
}

int main(int argc, char **argv) {
	g_dc.clk_mgr = &g_clk;
	g_dc.res_pool = &g_pool;
	g_dc.caps.max_odm_combine_factor = 4;
	g_ctx.dc = &g_dc;
	struct dcn401_dsc enc;
	memset(&enc, 0, sizeof(enc));
	dsc401_construct(&enc, &g_ctx, 0, NULL, NULL, NULL);
	struct display_stream_compressor *dsc = &enc.base;

	printf("// Generated by tools/gen/pipegen/dscgen.sh from Linux %s: amdgpu's DSC configuration and PPS for DP SST, RGB\n",
	       argc > 1 ? argv[1] : "?");
	printf("// (dc_dsc_compute_config, default options; dsc2_get_packed_pps; dsc_prepare_config). Do not edit.\n");
	printf("static const uint8_t kDscSinks[][16] = {\n");
	for (unsigned s = 0; s < ARRAY_SIZE(kSinks); s++) {
		printf("\t{");
		for (int i = 0; i < 16; i++) printf(" 0x%02x,", kSinks[s][i]);
		printf(" },\n");
	}
	printf("};\n\nstatic const DscRef kDscRef[] = {\n");
	int n = 0, on = 0;
	for (unsigned s = 0; s < ARRAY_SIZE(kSinks); s++)
	for (unsigned ti = 0; ti < ARRAY_SIZE(kTimings); ti++)
	for (unsigned bi = 0; bi < ARRAY_SIZE(kBpc); bi++)
	for (unsigned li = 0; li < ARRAY_SIZE(kLinks); li++)
	for (unsigned ci = 0; ci < ARRAY_SIZE(kClocks); ci++) {
		g_dscclk = kClocks[ci].dscclk; g_dispclk = kClocks[ci].dispclk;
		struct dsc_dec_dpcd_caps caps;
		memset(&caps, 0, sizeof(caps));
		if (!dc_dsc_parse_dsc_dpcd(&g_dc, kSinks[s], kNoBranch, &caps)) { fprintf(stderr, "dscgen: sink %u not parsed\n", s); return 1; }

		const struct tim *t = &kTimings[ti];
		struct dc_crtc_timing tm;
		memset(&tm, 0, sizeof(tm));
		tm.h_addressable = t->ha; tm.v_addressable = t->va; tm.h_total = t->ht; tm.v_total = t->vt;
		tm.pix_clk_100hz = t->khz * 10;
		tm.pixel_encoding = PIXEL_ENCODING_RGB;
		tm.display_color_depth = depth(kBpc[bi]);

		struct dc_dsc_config_options opt;
		dc_dsc_get_default_config_option(&g_dc, &opt);
		const uint32_t kbps = link_kbps(kLinks[li].lanes, kLinks[li].rate);
		struct dc_dsc_config cfg;
		memset(&cfg, 0, sizeof(cfg));
		/* amdgpu enables DSC only when the stream does not fit the link (apply_dsc_policy_for_stream: is_dsc_need) */
		bool need = dc_bandwidth_in_kbps_from_timing(&tm, DC_LINK_ENCODING_DP_8b_10b) > kbps;
		bool ok = need && dc_dsc_compute_config(dsc, &caps, &opt, kbps, &tm, DC_LINK_ENCODING_DP_8b_10b, &cfg);

		uint8_t pps[128];
		memset(pps, 0, sizeof(pps));
		struct dsc_reg_values rv;
		struct dsc_optc_config optc;
		memset(&rv, 0, sizeof(rv)); memset(&optc, 0, sizeof(optc));
		if (ok) {
			struct dsc_config dc = {
				.pic_width = t->ha, .pic_height = t->va, .pixel_encoding = PIXEL_ENCODING_RGB,
				.color_depth = depth(kBpc[bi]), .is_odm = false, .dc_dsc_cfg = cfg, .dsc_padding = 0 };
			if (!dsc->funcs->dsc_get_packed_pps(dsc, &dc, pps) || !dsc_prepare_config(&dc, &rv, &optc)) {
				fprintf(stderr, "dscgen: PPS refused\n"); return 1;
			}
			on++;
		}
		printf("\t{ %u, %4u, %4u, %4u, %4u, %7u, %2u, %u, 0x%02x, %7u, %7u,  %u, %2u, %2u, %4u, %3u, %u, %2u, %u, 0x%08x, %6u, %5u,\n\t  {",
		       s, t->ha, t->va, t->ht, t->vt, t->khz, kBpc[bi], kLinks[li].lanes, kLinks[li].rate,
		       kClocks[ci].dscclk, kClocks[ci].dispclk, ok, cfg.num_slices_h, cfg.num_slices_v,
		       ok ? (unsigned)rv.pps.slice_height : 0, cfg.bits_per_pixel, cfg.block_pred_enable, cfg.linebuf_depth,
		       cfg.version_minor, optc.bytes_per_pixel, rv.rc_buffer_model_size, (unsigned)rv.pps.slice_chunk_size);
		if (ok) for (int i = 0; i < 128; i++) printf("%s0x%02x,", i % 16 ? " " : i ? "\n\t   " : " ", pps[i]);
		printf(" } },\n");
		n++;
	}
	printf("};\n");
	fprintf(stderr, "dscgen: %d cases, %d with DSC\n", n, on);
	return 0;
}
