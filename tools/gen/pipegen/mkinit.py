#!/usr/bin/env python3
"""mkinit.py <dcn_4_1_0_offset.h> <pipegen init trace> <linux commit> > src/dcn_init_linux.inc

dcn401_init_hw on display hardware with nothing running (pipegen's "init" scenario), as the table src/dcninit.cpp
turns into steps. Marks are dropped (what they stood for is in the header comment); every other step is kept in
Linux's order, named after the Linux function and the register."""
import collections, re, sys

hdr, trace, commit = sys.argv[1:4]

base, off = {}, {}
for line in open(hdr):
    m = re.match(r'#define (reg\w+?)(_BASE_IDX)?\s+(0x[0-9a-fA-F]+|\d+)\s*$', line)
    if m:
        (base if m.group(2) else off)[m.group(1)[3:]] = int(m.group(3), 0)
names = collections.defaultdict(list)
for n, o in off.items():
    if n in base:
        names[(base[n], o)].append(n)

def name(seg, dword):
    n = names.get((seg, dword))
    if not n:
        sys.exit(f'mkinit: no register at segment {seg} dword 0x{dword:04x}')
    return n[0]

tables = {'otgoff0': [], 'otgoff1': [], 'otgoff2': [], 'otgoff3': [], 'init_hw': []}
out, marks = None, []
for line in open(trace):
    p = line.split()
    if not p:
        continue
    kind = p[0]
    func = line.split(';')[-1].strip() if ';' in line else ''
    if kind == 'MARK':
        if p[1].startswith('begin:') and p[1][6:] in tables:
            out = tables[p[1][6:]]
        else:
            marks.append(p[1])
        continue
    if out is None:
        out = tables['init_hw']   # before any section: object construction (the DSCs'), part of starting up
    if kind in ('W', 'U'):
        seg, dword, mask, value = int(p[1]), int(p[2], 16), int(p[3], 16), int(p[4], 16)
        if mask == 0:
            sys.exit(f'mkinit: {func} {name(seg, dword)}: every bit depends on what was read: no step can say it')
        op = 'W' if kind == 'W' and mask == 0xffffffff else 'U'
        out.append((op, seg, dword, mask, value, 0, f'{func} {name(seg, dword)}'))
    elif kind == 'WAIT':
        seg, dword, mask, value, us = int(p[1]), int(p[2], 16), int(p[3], 16), int(p[4], 16), int(p[5])
        out.append(('T', seg, dword, mask, value, us, f'{func} {name(seg, dword)}'))
    elif kind == 'DELAY':
        out.append(('D', 0, 0, 0, 0, int(p[1]), func))
    elif kind == 'COPY':
        seg, dword, sseg, sdword = int(p[1]), int(p[2], 16), int(p[3]), int(p[4], 16)
        if seg != sseg:
            sys.exit(f'mkinit: a copy between segments ({func})')
        out.append(('C', seg, dword, 0, 0, sdword, f'{func} {name(seg, dword)} = {name(sseg, sdword)}'))
    else:
        sys.exit(f'mkinit: unknown step {kind}')

init, otgoff = tables['init_hw'], [tables[f'otgoff{i}'] for i in range(4)]
if len({len(t) for t in otgoff}) != 1:
    sys.exit('mkinit: the four OTGs stop in different numbers of steps')
print(f'''// GENERATED by tools/gen/pipegen (run.sh init) from Linux {commit[:12]} (drivers/gpu/drm/amd/display). Do not edit.
//
// dcn401_init_hw on display hardware with nothing running, as after a power loss: every timing generator and
// DIG back end off, no blender feeding an OPP, the IP request window closed, the four connectors' link encoders
// (DisplayPort on links 0-1, HDMI on 2-3). Left out of the recording as marks: the clock manager's
// update_clocks (the kext raises the display clocks itself, src/clk.cpp) and dc_allow_idle_optimizations
// (idle power features this card does not use here). Linux does not program the DCHUB global timer here: it
// requires it running (src/dcninit.cpp's timerSteps start it). {len(init)} steps; before them, for a warm card, each
// running timing generator stopped as Linux stops one (optc401_disable_crtc), {len(otgoff[0])} steps an OTG.
//
// {{ op, segment, dword, mask, value, arg, what }}: 'W' reg = value; 'U' reg = (reg & ~mask) | value; 'T' wait
// until (reg & mask) == value, arg microseconds at most; 'C' reg = the register at dword arg of the segment;
// 'D' wait arg microseconds.''')
def rows(steps, indent):
    for op, seg, dword, mask, value, arg, what in steps:
        a = f'0x{arg:04x}' if op == 'C' else f'{arg}'
        print(f'{indent}{{ \'{op}\', {seg}, 0x{dword:04x}, 0x{mask:08x}, 0x{value:08x}, {a:>6}, "{what}" }},')
print(f'static const DcnInit::Gen kDcnOtgOffLinux[4][{len(otgoff[0])}] = {{')
for t in otgoff:
    print('\t{')
    rows(t, '\t\t')
    print('\t},')
print('};')
print('static const DcnInit::Gen kDcnInitLinux[] = {')
rows(init, '\t')
print('};')
sys.stderr.write(f'mkinit: {len(init)} steps, {len(otgoff[0])} to stop each OTG; marks dropped: {", ".join(sorted(set(marks)))}\n')
