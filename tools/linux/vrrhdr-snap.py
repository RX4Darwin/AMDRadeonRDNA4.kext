def card():
    for c in sorted(glob.glob('/sys/class/drm/card[0-9]*')):
        if not os.path.isdir(c + '/device/ip_discovery'):
            continue
        try:
            if open(c + '/device/vendor').read().strip() == '0x1002':
                return c
        except OSError:
            pass
    sys.exit('no AMD card with ip_discovery in /sys/class/drm')

c = card()
pci = os.path.basename(os.path.realpath(c + '/device'))
bases = None
for f in ('/device/ip_discovery/die/0/DMU/0/base_addr', '/device/ip_discovery/die/0/271/0/base_addr'):
    if os.path.exists(c + f):
        bases = [int(x, 0) for x in open(c + f).read().split()]
        break
if not bases:
    sys.exit('no DMU base addresses under ' + c)
regs_file = None
for d in glob.glob('/sys/kernel/debug/dri/*'):
    try:
        if pci in open(d + '/name').read() and os.path.exists(d + '/amdgpu_regs'):
            regs_file = d + '/amdgpu_regs'
            break
    except OSError:
        pass
if not regs_file:
    sys.exit('no amdgpu_regs in /sys/kernel/debug/dri for ' + pci + ' (debugfs mounted? Secure Boot lockdown?)')
print(f'card {c} ({pci}), {regs_file}, DMU bases {" ".join(hex(b) for b in bases)}', flush=True)

fd = os.open(regs_file, os.O_RDONLY)
out = open(sys.argv[1], 'w')
out.write(f'# dsc-snap {pci} DMU bases {" ".join(hex(b) for b in bases)}\n')
out.flush(); os.fsync(out.fileno())
n = 0
for line in REGS.split('\n'):
    if not line.strip():
        continue
    name, seg, dword = line.split()
    addr = (bases[int(seg)] + int(dword, 16)) * 4
    out.write(f'# reading {name}\n'); out.flush(); os.fsync(out.fileno())
    v = struct.unpack('<I', os.pread(fd, 4, addr))[0]
    out.write(f'{name} {seg} {dword} {addr} 0x{v:08x}\n'); out.flush(); os.fsync(out.fileno())
    n += 1
out.close()
print(f'{n} registers read into {sys.argv[1]}')

for aux in sorted(glob.glob(c + '-DP-*/drm_dp_aux*')):
    dev = '/dev/' + os.path.basename(aux)
    try:
        f = os.open(dev, os.O_RDONLY)
        for off in (0x107, 0x2210):
            v = os.pread(f, 1, off)
            with open(sys.argv[1], 'a') as o:
                o.write(f'DPCD {os.path.basename(os.path.dirname(aux))} 0x{off:04x} 0x{v[0]:02x}\n')
        os.close(f)
    except OSError as e:
        print(dev, e)

