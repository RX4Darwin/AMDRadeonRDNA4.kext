main() {
	local args="$*"
	while [ $# -gt 0 ]; do
		case "$1" in
		--auto-xrandr) AUTO_XRANDR=1 ;;
		--no-trace) NO_TRACE=1 ;;
		--snap-only) SNAP_ONLY=1 NO_TRACE=1 ;;
		-h|--help) usage; exit 0 ;;
		*) echo "unknown option: $1 (see --help)"; exit 1 ;;
		esac
		shift
	done
	if [ "$(id -u)" -ne 0 ] && [ "${RDNA4_SKIP_ROOT:-0}" != 1 ]; then
		echo "run with sudo: sudo bash $0 $args"
		exit 1
	fi
	mkdir -p "$OUT" || exit 1
	trap on_signal INT TERM
	mark start

	hdr "preflight"
	if ! find_card; then
		say "!! no amdgpu card found under $SYSFS/class/drm (is amdgpu loaded?)"
		exit 1
	fi
	say "GPU: $CARD  $BDF  [$PCI_ID]"
	case "$PCI_ID" in *0x7550) ;; *) say "!! not a Navi 48 (0x7550) — capturing anyway" ;; esac
	if find_dri; then
		say "debugfs: $DRI"
	else
		say "!! no debugfs dri dir for $BDF (debugfs off? kernel lockdown?)"
	fi
	[ -n "$DRI" ] && [ ! -e "$DRI/amdgpu_regs" ] && say "!! $DRI has no amdgpu_regs"
	dmu_bases || say "!! DMU bases not found in ip_discovery — using built-in default"
	say "DMU bases: $DMU_BASES_STR  [$DMU_BASES_SRC]"
	resolve_regs
	say "register list: $(grep -c . "$OUT/reglist-resolved.txt") DCN registers"
	choose_reader || say "!! no working register reader — snapshots will say SKIP:noreader"
	[ "$HAVE_PY" = 1 ] || say "note: python3 missing — slower dd reads, approximate step clock ($(install_hint python3))"
	case "$(cat "$SYSFS/kernel/security/lockdown" 2>/dev/null)" in
	*"[confidentiality]"*) say "!! kernel lockdown=confidentiality: bpftrace will fail — disable Secure Boot" ;;
	*"[integrity]"*) say "note: kernel lockdown=integrity (Secure Boot on)" ;;
	esac

	hdr "static info"
	collect_system
	collect_fw
	collect_ipd
	collect_connectors

	hdr "snapshot: boot (current mode)"
	snap boot

	if [ "$SNAP_ONLY" = 1 ]; then
		finish
		exit 0
	fi

	hdr "DMUB trace"
	trace_start
	if [ "$AUTO_XRANDR" = 1 ] && ! xr_setup; then
		say "   falling back to interactive prompts"
		AUTO_XRANDR=0
	fi

	hdr "mode steps"
	run_steps
	finish
}

