# Candidates from dmub-trace.sh. The lowest-level ring submit sees every
# command (including cmd lists), so hook exactly one of those; the
# register-inbox path is disjoint, add it when present. Wrappers are a
# fallback (may be inlined). The union dmub_rb_cmd* is arg1 everywhere
# except dc_dmub_srv_cmd_list_queue_execute(srv, count, list) -> arg2.
pick_hooks() {
	local f
	HOOKS=""
	if [ -n "${RDNA4_DMUB_HOOKS:-}" ]; then HOOKS=$RDNA4_DMUB_HOOKS; return 0; fi
	for f in /sys/kernel/tracing/available_filter_functions \
	         "$DEBUGFS/tracing/available_filter_functions"; do
		[ -r "$f" ] && { AFF=$f; break; }
	done
	for f in dmub_srv_fb_cmd_queue dmub_srv_cmd_queue; do
		have_sym "$f" && { HOOKS="$f:arg1"; break; }
	done
	have_sym dmub_srv_reg_cmd_execute && HOOKS="$HOOKS dmub_srv_reg_cmd_execute:arg1"
	HOOKS=${HOOKS# }
	[ -n "$HOOKS" ] && return 0
	for f in dc_dmub_srv_cmd_run:arg1 dc_dmub_srv_cmd_list_queue_execute:arg2 \
	         dm_execute_dmub_cmd:arg1 dc_wake_and_execute_dmub_cmd:arg1 \
	         dc_dmub_srv_cmd_queue:arg1; do
		have_sym "${f%%:*}" && { HOOKS=$f; return 0; }
	done
	return 1
}

# One line per command: nsecs, 16 dwords of the 64-byte union dmub_rb_cmd,
# hooked function. nsecs = ktime_get_ns (CLOCK_MONOTONIC).
bt_program() {
	local h fn a
	printf '%s\n' 'BEGIN { printf("# READY %llu\n", nsecs); }'
	for h in $HOOKS; do
		fn=${h%%:*} a=${h##*:}
		cat <<EOF
kprobe:$fn {
  \$p = $a;
  printf("%llu %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x %08x $fn\n",
    nsecs,
    *(uint32 *)(\$p + 0),  *(uint32 *)(\$p + 4),  *(uint32 *)(\$p + 8),  *(uint32 *)(\$p + 12),
    *(uint32 *)(\$p + 16), *(uint32 *)(\$p + 20), *(uint32 *)(\$p + 24), *(uint32 *)(\$p + 28),
    *(uint32 *)(\$p + 32), *(uint32 *)(\$p + 36), *(uint32 *)(\$p + 40), *(uint32 *)(\$p + 44),
    *(uint32 *)(\$p + 48), *(uint32 *)(\$p + 52), *(uint32 *)(\$p + 56), *(uint32 *)(\$p + 60));
}
EOF
	done
}

trace_start() {
	local bt_args=""
	if [ "$NO_TRACE" = 1 ]; then TRACE_STATUS="disabled (--no-trace)"; say "DMUB trace disabled (--no-trace)"; return 1; fi
	if ! command -v bpftrace >/dev/null 2>&1; then
		TRACE_STATUS="bpftrace not installed"
		say "!! bpftrace not found — continuing WITHOUT the DMUB command trace"
		say "   (registers only). For the full capture: $(install_hint bpftrace)"
		return 1
	fi
	if ! pick_hooks; then
		TRACE_STATUS="no DMUB submit symbol in this kernel"
		say "!! none of the DMUB submit functions is in kallsyms/available_filter_functions"
		say "   — continuing without the trace (set RDNA4_DMUB_HOOKS=\"fn:arg1\" to force one)"
		return 1
	fi
	bt_program > "$OUT/dmub-trace.bt"
	case "$(bpftrace --help 2>&1)" in
	*"'line'"*) bt_args="-B line" ;;      # flush every event to dmub-raw.txt
	*"'none'"*) bt_args="-B none" ;;
	esac
	say "DMUB trace: hooking $HOOKS (bpftrace $bt_args)"
	# shellcheck disable=SC2086
	bpftrace $bt_args "$OUT/dmub-trace.bt" > "$OUT/dmub-raw.txt" 2> "$OUT/dmub-trace.err" &
	BPID=$!
	for _ in $(seq 1 120); do
		grep -q '^# READY' "$OUT/dmub-raw.txt" 2>/dev/null && break
		kill -0 "$BPID" 2>/dev/null || break
		sleep 0.5
	done
	if ! grep -q '^# READY' "$OUT/dmub-raw.txt" 2>/dev/null; then
		kill "$BPID" 2>/dev/null
		wait "$BPID" 2>/dev/null
		BPID=""
		TRACE_STATUS="bpftrace failed to start"
		say "!! bpftrace did not start — continuing WITHOUT the DMUB trace. Its error:"
		head -15 "$OUT/dmub-trace.err" | sed 's/^/   /' | tee -a "$OUT/capture.log"
		case "$(cat "$SYSFS/kernel/security/lockdown" 2>/dev/null)" in
		*"[confidentiality]"*)
			say "   kernel lockdown=confidentiality blocks bpftrace — disable Secure Boot for this capture" ;;
		*"[integrity]"*)
			say "   (kernel lockdown=integrity is on; if the error mentions lockdown, disable Secure Boot)" ;;
		esac
		return 1
	fi
	sleep 2   # BEGIN fires before the kprobes finish attaching
	mark trace-ready
	TRACE_STATUS="captured via $HOOKS"
	return 0
}

trace_stop() {
	local sig
	[ -n "$BPID" ] || return 0
	sleep 1
	for sig in INT TERM KILL; do
		kill -0 "$BPID" 2>/dev/null || break
		kill -"$sig" "$BPID" 2>/dev/null
		for _ in 1 2 3 4 5 6; do
			kill -0 "$BPID" 2>/dev/null || break
			sleep 0.5
		done
	done
	wait "$BPID" 2>/dev/null
	BPID=""
}

# Header (union dmub_rb_cmd.header): type[7:0] subtype[15:8] ret[16]
# multi[17] reg_based[18] payload_bytes[29:24]. Hints decode the MAINLINE
# payload layouts (atomfirmware.h v1_5/v1_6/v1_7) — if the GOP firmware
# speaks another dialect they are only guesses; the raw dwords are exact.
# shellcheck disable=SC2016  # awk program
AWK_DMUB='
function nm(arr, k) { return (k in arr) ? arr[k] : ("?" k) }
function table(arr, s,   a, kv, i, n) {
	n = split(s, a, " ")
	for (i = 1; i <= n; i++) { split(a[i], kv, ":"); arr[kv[1]] = kv[2] }
}
function stepof(t,   i, best) {
	best = 0
	for (i = 1; i <= ns; i++) if (ST[i] <= t && SE[i] != "trace-ready") best = i
	if (!best || SE[best] == "start") return "pre"
	if (SE[best] == "begin") return SL[best]
	if (SE[best] == "snap") return "idle@" SL[best]
	if (SE[best] == "skip") return "skipped@" SL[best]
	if (SE[best] == "end") return "post"
	return SE[best]
}
function hint(t, s, d1, d2, d3) {
	if (t != 128) return ""
	if (s == 0) return sprintf("dig=%d action=%s mode=%s lanes=%d pclk=%.2fMHz bpc=%d dplinkrate=%d",
		byte(d1, 0), nm(ENA, byte(d1, 1)), nm(EM, byte(d1, 2)), byte(d1, 3), d2 / 100, byte(d3, 0), byte(d3, 1))
	if (s == 1) return sprintf("phy=%d action=%s mode=%s lanes=%d symclk=%.2fMHz hpd=%d digfe=0x%s connobj=0x%s",
		byte(d1, 0), nm(TXA, byte(d1, 1)), nm(EM, byte(d1, 2)), byte(d1, 3), d2 / 100, byte(d3, 0), hex2(byte(d3, 1)), hex2(byte(d3, 2)))
	if (s == 2) return sprintf("pixclk=%.4fMHz pll=%d encobj=0x%s encmode=%s misc=0x%s crtc=%d deepcolor=%d",
		d1 / 10000, byte(d2, 0), hex2(byte(d2, 1)), nm(EM, byte(d2, 2)), hex2(byte(d2, 3)), byte(d3, 0), byte(d3, 1))
	if (s == 3) return sprintf("pipe=%d enable=%d", byte(d1, 0), byte(d1, 1))
	if (s == 15) return sprintf("action=%d", byte(d1, 0))
	if (s == 26) return sprintf("phy=%d is_usb=%d dp_alt_disable=%d is_dp4=%d", byte(d1, 0), byte(d1, 1), byte(d1, 2), byte(d1, 3))
	if (s == 28) return sprintf("domain_inst=%d power_gate=%d", byte(d1, 0) % 64, int(byte(d1, 0) / 64) % 2)
	if (s == 29) return sprintf("phy=%d mode=%d lanes=%d symclk=%.4fMHz", byte(d1, 0), byte(d1, 1), byte(d1, 2), d2 / 10000)
	return "NOT A MAINLINE VBIOS SUBTYPE (GOP firmware dialect?) — use the raw dwords"
}
BEGIN {
	table(TN, "0:NULL 1:type1(deprecated) 2:type2(deprecated) 3:type3(deprecated) 4:type4(deprecated) 5:PLAT_54186_WA 6:QUERY_FEATURE_CAPS 8:GET_VISUAL_CONFIRM_COLOR 64:PSR 65:MALL 66:ABM 67:UPDATE_DIRTY_RECT 68:UPDATE_CURSOR_INFO 69:HW_LOCK 70:DP_AUX_ACCESS 71:OUTBOX1_ENABLE 72:IDLE_OPT 73:CLK_MGR 74:PANEL_CNTL 75:CAB_FOR_SS 76:FW_ASSISTED_MCLK_SWITCH 77:DPIA 79:EDID_CEA 82:QUERY_HPD_STATE 83:REPLAY 85:SECURE_DISPLAY 86:DPIA_HPD_INT_ENABLE 87:CACP 88:PSP 89:FUSED_IO 90:LSDMA 91:IPS 92:CURSOR_OFFLOAD 93:SMART_POWER_OLED 94:PR 95:IHC 96:BOOT_TIME_CRC 97:PANEL_POLARITY 128:VBIOS")
	table(VN, "0:DIGX_ENCODER_CONTROL 1:DIG1_TRANSMITTER_CONTROL 2:SET_PIXEL_CLOCK 3:ENABLE_DISP_POWER_GATING 15:LVTMA_CONTROL 26:TRANSMITTER_QUERY_DP_ALT 28:DOMAIN_CONTROL 29:TRANSMITTER_SET_PHY_FSM")
	table(TXA, "0:DISABLE 1:ENABLE 2:LCD_BLOFF 3:LCD_BLON 4:BL_BRIGHTNESS 5:SELFTEST_START 6:SELFTEST_STOP 7:INIT 8:DISABLE_OUTPUT 9:ENABLE_OUTPUT 10:SETUP 11:SETUP_VSEMPH 12:POWER_ON 13:POWER_OFF")
	table(ENA, "0:DISABLE_DIG 1:ENABLE_DIG 8:DP_LT_START 9:DP_LT_PAT1 10:DP_LT_PAT2 11:DP_LT_COMPLETE 12:DP_VIDEO_OFF 13:DP_VIDEO_ON 15:STREAM_SETUP 16:SETUP_PANEL_MODE 17:LINK_SETUP 18:ENCODER_BLANK 19:DP_LT_PAT3 20:DP_LT_PAT4")
	table(EM, "0:DP 1:LVDS 2:DVI 3:HDMI 5:DP_MST 15:CRT 16:DVO")
}
FILENAME == ARGV[1] {
	if (NF >= 2 && $1 ~ /^[0-9]+$/) { ns++; ST[ns] = $1 + 0; SE[ns] = $2; SL[ns] = (NF >= 3) ? $3 : "-"
		if ($2 == "trace-ready") ready_mono = $1 + 0 }
	next
}
/^# READY/ { ready_bt = $3 + 0; next }
$1 !~ /^[0-9]+$/ || NF < 17 { next }
{
	t = $1 + 0
	if (!ref) ref = ready_bt ? ready_bt : t
	hdr = hex2dec($2)
	ty = hdr % 256; sb = int(hdr / 256) % 256; pl = int(hdr / 16777216) % 64
	lab = (ty == 128) ? ("VBIOS/" ((sb in VN) ? VN[sb] : ("sub" sb))) : ((ty in TN) ? TN[ty] : ("type" ty))
	if (ty == 128 && !(sb in VN)) UNKSUB[sb]++
	if (ty != 128 && !(ty in TN)) UNKTYPE[ty]++
	st = stepof(t)
	if (!(st in SEEN)) { SEEN[st] = 1; ORD[++nord] = st }
	C[st, lab]++; if (!((st, lab) in FIRST)) { FIRST[st, lab] = 1; LBL[st, ++NL[st]] = lab }
	fn = (NF >= 18) ? $18 : "?"
	dw = ""; for (i = 3; i <= 17; i++) dw = dw " " $i
	ncmd++
	line = sprintf("%-16s %+12.3fms %-30s hdr=%s pl=%2d |%s  [%s]", st, (t - ref) / 1000000, lab, $2, pl, dw, fn)
	L[ncmd] = line
	h = hint(ty, sb, hex2dec($3), hex2dec($4), hex2dec($5))
	if (h != "") L[ncmd] = line "\n" sprintf("%-16s %14s   ; %s", "", "", h)
	if (ty == 128) V[++nv] = sprintf("%-16s %+12.3fms %s %s%s", st, (t - ref) / 1000000, lab, $2, dw)
}
END {
	printf "# DMUB inbox commands captured by linux-capture.sh (hook: %s)\n", hooks
	printf "# columns: step  time-since-trace-start  type/subtype  header  payload_bytes | dwords 1..15  [hooked fn]\n"
	printf "# step = the prompt window the command fell in; idle@X = after snapshot X, before the next step\n"
	if (ready_bt && ready_mono) printf "# clock check: bpftrace READY %.0f ns, script trace-ready mark %.0f ns (delta %.1f ms, expect ~2000)\n", ready_bt, ready_mono, (ready_mono - ready_bt) / 1000000
	printf "# %d commands\n\n", ncmd
	for (i = 1; i <= ncmd; i++) print L[i]
	printf "\n=== per-step command counts ===\n"
	for (i = 1; i <= nord; i++) {
		st = ORD[i]; printf "%s:\n", st
		for (k = 1; k <= NL[st]; k++) printf "  %5d  %s\n", C[st, LBL[st, k]], LBL[st, k]
	}
	printf "\n=== VBIOS (type 128) commands, full 16 dwords — the replay candidates ===\n"
	for (i = 1; i <= nv; i++) print V[i]
	if (!nv) print "(none)"
	u = ""; for (k in UNKSUB) u = u " sub" k "(x" UNKSUB[k] ")"
	printf "\nnon-mainline VBIOS subtypes seen:%s\n", (u == "" ? " none — mainline dialect so far" : u)
	u = ""; for (k in UNKTYPE) u = u " type" k "(x" UNKTYPE[k] ")"
	if (u != "") printf "unknown command types seen:%s\n", u
}'

decode_trace() {
	local raw="$OUT/dmub-raw.txt" dec="$OUT/dmub-decoded.txt"
	if [ ! -s "$raw" ]; then
		echo "(no DMUB trace: $TRACE_STATUS)" > "$dec"
		return 0
	fi
	awk -v hooks="$HOOKS" "$AWK_LIB$AWK_DMUB" "$OUT/steps.txt" "$raw" > "$dec"
}

# diff-<a>-vs-<b>.txt: registers whose value changed between consecutive
# snapshots. "volatile" marks counters/status that change on their own.
# shellcheck disable=SC2016  # awk program
AWK_DIFF='
BEGIN { printf "# register changes %s -> %s (changed only; volatile = counter/status that moves by itself)\n# NAME base_idx dword_off byte_addr  old -> new  xor\n", a, b }
FILENAME == ARGV[1] { if ($1 !~ /^#/ && NF >= 5) old[$1] = $5; next }
$1 !~ /^#/ && NF >= 5 && ($1 in old) && old[$1] != $5 {
	x = ""
	if (old[$1] ~ /^0x/ && $5 ~ /^0x/) x = "  xor=0x" hex8(xor32(hex2dec(old[$1]), hex2dec($5)))
	vol = ($1 ~ /(STATUS|TIMER_CURRENT|READ_LINE|_WPTR|_RPTR|SCRATCH|INTERRUPT|DEBUG|FRAME|POSITION|INUSE|CRC|GPINT|INBOX|OUTBOX|LATCH_VALUE|DCC_STAT)/) ? "  (volatile)" : ""
	printf "%-48s %s %s %s  %s -> %s%s%s\n", $1, $2, $3, $4, old[$1], $5, x, vol
	n++
}
END { printf "# %d registers changed\n", n }'

make_diffs() {
	local prev="" s
	for s in $SNAPS; do
		if [ -n "$prev" ]; then
			awk -v a="$prev" -v b="$s" "$AWK_LIB$AWK_DIFF" \
				"$OUT/regs-$prev.txt" "$OUT/regs-$s.txt" > "$OUT/diff-$prev-vs-$s.txt"
			say "  diff-$prev-vs-$s.txt: $(tail -1 "$OUT/diff-$prev-vs-$s.txt" | sed 's/^# //')"
		fi
		prev=$s
	done
}

