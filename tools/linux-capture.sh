have_sym() {
	if [ -n "$AFF" ]; then
		awk -v s="$1" '$1 == s {f = 1; exit} END {exit !f}' "$AFF"
	else
		awk -v s="$1" '$3 == s {f = 1; exit} END {exit !f}' /proc/kallsyms
