# Package-manager hint for the running distro.
install_hint() {
	local ids
	# shellcheck source=/dev/null
	ids=" $( (. /etc/os-release 2>/dev/null; echo "${ID:-} ${ID_LIKE:-}") ) "
	case "$ids" in
	*" arch "*) echo "pacman -S $*" | sed 's/python3/python/' ;;
	*" fedora "*|*" rhel "*|*" centos "*) echo "dnf install $*" ;;
	*" suse "*|*" opensuse "*) echo "zypper install $*" ;;
	*" debian "*|*" ubuntu "*) echo "apt install $*" ;;
	*) echo "apt install $* (or dnf install / pacman -S)" ;;
	esac
}

# CLOCK_MONOTONIC in ns — the clock bpftrace's nsecs uses (ktime_get_ns), so
# step markers and DMUB commands share one timeline. /proc/timer_list "now
# at" is ktime_get() too; /proc/uptime is only an approximation (boottime).
mono_ns() {
	local t=""
	[ "$HAVE_PY" = 1 ] && t=$(python3 -c 'import time; print(time.monotonic_ns())' 2>/dev/null)
	[ -n "$t" ] || t=$(awk '/^now at/ {print $3; exit}' /proc/timer_list 2>/dev/null)
	[ -n "$t" ] || t=$(awk '{printf "%.0f\n", $1 * 1000000000}' /proc/uptime)
	echo "$t"
}
# steps.txt: "<mono_ns> <event> <label>" — events start, trace-ready,
# begin <step>, snap <label>, skip <step>, end.
mark() { echo "$(mono_ns) $1 ${2:--}" >> "$OUT/steps.txt"; }

