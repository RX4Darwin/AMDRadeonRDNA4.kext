#!/bin/bash
#
# linux-capture.sh — capture amdgpu's HDMI mode-set ground truth under Linux.
#
# Supersedes dmub-trace.sh. RDNA4FB is gaining native mode setting for the
# HDMI monitor (1080p 60-75 Hz, TMDS) on the RX 9070 XT (Navi 48, DCN 4.1.0).
# The GOP-loaded DMUB firmware may speak a VBIOS-command dialect that does
# not match mainline, so instead of guessing we record what a *working*
# driver (Linux amdgpu, same machine, same firmware) does for known modes:
#
#   1. the DMUB inbox command stream: bpftrace kprobe on amdgpu's DMUB
#      submit function, 16 dwords per union dmub_rb_cmd, each command
#      attributed to the step (mode change) that caused it;
#   2. a ~1500-register DCN snapshot after every step (OTG/ODM/HUBP/DPP/
#      DSCL/MPC/OPP/DIG/DIO/VPG/DCCG/DMCUB/PHY/HUBBUB) read through debugfs
#      amdgpu_regs, plus register diffs between consecutive steps — the
#      fallback programming recipe if DMUB replay from macOS doesn't work;
#   3. context: IP-discovery segment bases, firmware versions (DMCUB), EDIDs,
#      the DRM atomic state and amdgpu's DTN hardware-state log per step.
#
# Run as root on the dual-boot Linux (Debian/Ubuntu/Fedora/Arch...):
#   sudo bash tools/linux-capture.sh                # interactive (Wayland or X11)
#   sudo bash tools/linux-capture.sh --auto-xrandr  # X11 only: xrandr switches modes
#   sudo bash tools/linux-capture.sh --no-trace     # registers only, skip bpftrace
#   sudo bash tools/linux-capture.sh --snap-only    # one register snapshot, no steps
# Output: rdna4-capture-<timestamp>/ + .tar.gz in the current directory.
#
# Needs bash, awk, coreutils. Recommended: bpftrace (the DMUB trace — without
# it the script still captures registers and says so) and python3 (fast
# register reads, exact CLOCK_MONOTONIC step markers). If Secure Boot puts
# the kernel in lockdown=confidentiality, bpftrace cannot read kernel memory:
# disable Secure Boot for the capture session.
#
# HOW TO DRIVE IT: follow the prompts. Each step asks you to switch mode in
# your desktop's display settings (click "Keep changes"), wait for a stable
# picture, then press Enter (s + Enter skips a step, e.g. if 75 Hz is not
# offered). The last step is a physical HDMI unplug/replug, which forces
# amdgpu through the full link/PHY/pixel-clock bring-up — the sequence
# RDNA4FB has to replay.
#
# SEND BACK: the rdna4-capture-<timestamp>.tar.gz printed at the end. Copy it
# to Windows (USB stick, or mount the Windows partition — commands printed)
# and put it in C:\Users\miguer\Documents\tools\RDNA4FB\captures\.
#
# Read-only: registers are only ever read, never written. Indirect data-port
# registers (VPG/RDPCS/DPCSSYS *_DATA) are listed but not read unless
# RDNA4_READ_DATA_PORTS=1 (a read can advance the port's index). The only
# system change is mounting debugfs if it is not mounted yet.
#
# Test/override knobs (env): RDNA4_SYSFS_ROOT, RDNA4_DEBUGFS_ROOT,
# RDNA4_DEBUGFS_DIR, RDNA4_CARD (e.g. card1), RDNA4_DMU_BASES ("0x12 0xc0 ..."),
# RDNA4_READER (auto|debugfs|dd|bar5), RDNA4_READ_DATA_PORTS=1,
# RDNA4_DMUB_HOOKS ("fn:arg1 ..."), RDNA4_OUT_BASE, RDNA4_SKIP_ROOT=1,
# RDNA4_LIB_ONLY=1 (source the functions without running main).
#

set -u
