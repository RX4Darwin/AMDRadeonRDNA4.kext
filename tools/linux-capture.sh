# xrandr as the desktop user (root usually has no X cookie).
xr() {
	local home
	if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ] && command -v sudo >/dev/null 2>&1; then
		home=$(getent passwd "$SUDO_USER" | cut -d: -f6)
		sudo -u "$SUDO_USER" env DISPLAY="${DISPLAY:-:0}" \
			XAUTHORITY="${XAUTHORITY:-$home/.Xauthority}" xrandr "$@"
	else
		DISPLAY="${DISPLAY:-:0}" xrandr "$@"
	fi
}

xr_setup() {
	local q
	command -v xrandr >/dev/null 2>&1 || { say "!! --auto-xrandr: xrandr not installed"; return 1; }
	if ! q=$(xr --query 2>&1); then
		say "!! --auto-xrandr: cannot talk to the X server: $(echo "$q" | head -1)"
		return 1
	fi
	printf '%s\n' "$q" > "$OUT/xrandr-before.txt"
	XR_OUT=$(printf '%s\n' "$q" | awk '$2 == "connected" && $1 ~ /^HDMI/ {print $1; exit}')
	[ -n "$XR_OUT" ] || XR_OUT=$(printf '%s\n' "$q" | awk '$2 == "connected" {print $1; exit}')
	case "$XR_OUT" in
	"") say "!! --auto-xrandr: no connected output"; return 1 ;;
	XWAYLAND*) say "!! --auto-xrandr: this is a Wayland session (XWayland can't set modes)"; return 1 ;;
	esac
	say "--auto-xrandr: driving X output $XR_OUT"
	return 0
}

# do_step <label> <instruction> [WxH rate]  (xrandr args only in auto mode)
do_step() {
	local label=$1 msg=$2 mode=${3:-} rate=${4:-} ans
	mark begin "$label"
	if [ "$AUTO_XRANDR" = 1 ] && [ -n "$mode" ]; then
		say ""
		say ">>> STEP $label [auto]: xrandr --output $XR_OUT --mode $mode --rate $rate"
		if xr --output "$XR_OUT" --mode "$mode" --rate "$rate" >> "$OUT/xrandr.log" 2>&1; then
			sleep 4
			snap "$label"
			return 0
		fi
		say "    xrandr failed (mode/rate not offered?) — do it by hand instead"
	fi
	say ""
	say ">>> STEP $label: $msg"
	say "    Wait for a stable picture, then press Enter  (s + Enter = skip this step)"
	read -r ans || ans=s
	case "$ans" in
	s|S|skip)
		mark skip "$label"
		say "    skipped $label"
		return 0 ;;
	esac
	sleep 1
	snap "$label"
}

do_offon() {
	mark begin offon
	say ""
	say ">>> STEP offon [auto]: xrandr --output $XR_OUT --off, then --auto"
	xr --output "$XR_OUT" --off >> "$OUT/xrandr.log" 2>&1
	sleep 3
	xr --output "$XR_OUT" --auto >> "$OUT/xrandr.log" 2>&1
	sleep 5
	snap offon
}

run_steps() {
	do_step 1080p75 "set 1920x1080 @ 75 Hz in your display settings (click \"Keep changes\")" 1920x1080 75
	do_step 720p60  "set 1280x720 @ 60 Hz (click \"Keep changes\")" 1280x720 60
	do_step 1080p60 "set back to 1920x1080 @ 60 Hz (click \"Keep changes\")" 1920x1080 60
	[ "$AUTO_XRANDR" = 1 ] && do_offon
	do_step replug  "UNPLUG the HDMI cable, wait ~5 s, plug it back in and wait for the desktop"
	if [ "$AUTO_XRANDR" = 1 ]; then
		xr --output "$XR_OUT" --mode 1920x1080 --rate 60 >> "$OUT/xrandr.log" 2>&1
		xr --query > "$OUT/xrandr-after.txt" 2>&1
	fi
}

