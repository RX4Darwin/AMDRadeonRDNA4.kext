AWK_SUMMARY='
$1 !~ /^#/ && NF >= 5 {
	nreg++
	if ($5 ~ /^0x/) { v[$1] = hex2dec($5); nok++; if ($5 == "0x00000000") nz++; if ($5 == "0xffffffff") nff++ }
	else if ($5 ~ /^ERR/) nerr++
	else nskip++
}
END {
	printf "[%s] regs: %d listed, %d read (%d zero, %d all-ones), %d errors, %d skipped\n", label, nreg, nok, nz, nff, nerr, nskip
	for (i = 0; i < 4; i++) {
		p = "OTG" i "_OTG_"
		if (!((p "CONTROL") in v)) continue
		c = v[p "CONTROL"]
		if (!bits(c, 0, 1) && !bits(c, 16, 1)) { printf "[%s] OTG%d: off\n", label, i; continue }
		on++
		hb = v[p "H_BLANK_START_END"]; vb = v[p "V_BLANK_START_END"]
		printf "[%s] OTG%d: on  active=%dx%d total=%dx%d hsync=%d vsync=%d hblank_end=%d vblank_end=%d odm_src=0x%s\n", label, i,
			bits(hb, 0, 15) - bits(hb, 16, 15), bits(vb, 0, 15) - bits(vb, 16, 15),
			bits(v[p "H_TOTAL"], 0, 15) + 1, bits(v[p "V_TOTAL"], 0, 15) + 1,
			bits(v[p "H_SYNC_A"], 16, 15) - bits(v[p "H_SYNC_A"], 0, 15),
			bits(v[p "V_SYNC_A"], 16, 15) - bits(v[p "V_SYNC_A"], 0, 15),
			bits(hb, 16, 15), bits(vb, 16, 15), hex8(v["ODM" i "_OPTC_DATA_SOURCE_SELECT"])
	}
	for (i = 0; i < 4; i++) {
		p = "DIG" i "_"
		fe = bits(v[p "DIG_FE_EN_CNTL"], 0, 1); be = bits(v[p "DIG_BE_EN_CNTL"], 0, 1)
		if (!fe && !be) continue
		printf "[%s] DIG%d: FE_EN=%d BE_EN=%d fe_src_otg=%d BE_CNTL=0x%s HDMI_CONTROL=0x%s TMDS_CNTL=0x%s\n", label, i, fe, be,
			bits(v[p "DIG_FE_CNTL"], 0, 3), hex8(v[p "DIG_BE_CNTL"]), hex8(v[p "HDMI_CONTROL"]), hex8(v[p "TMDS_CNTL"])
	}
	if (nok && !on) printf "[%s] !! no OTG enabled — display off, or DMU bases wrong?\n", label
}'

snap() {
	local label=$1 f t
	f="$OUT/regs-$label.txt"
	t=$(mono_ns)
	echo "$t snap $label" >> "$OUT/steps.txt"
	{
		echo "# RDNA4FB DCN register snapshot: label=$label mono_ns=$t reader=$READER src=${REG_SRC:-none}"
		echo "# DMU segment bases (base_idx 0,1,..): $DMU_BASES_STR  [$DMU_BASES_SRC]"
		echo "# byte_addr = (base[base_idx] + dword_off) * 4   SKIP:dataport = indirect data port, not read"
		echo "# NAME base_idx dword_off byte_addr value"
		read_regs "$OUT/reglist-resolved.txt"
	} > "$f"
	if [ -n "$DRI" ]; then
		cat "$DRI/state" > "$OUT/drm-state-$label.txt" 2>/dev/null ||
			rm -f "$OUT/drm-state-$label.txt"
		cat "$DRI/amdgpu_dm_dtn_log" > "$OUT/dtn-$label.txt" 2>/dev/null ||
			rm -f "$OUT/dtn-$label.txt"
	fi
	awk -v label="$label" "$AWK_LIB$AWK_SUMMARY" "$f" | tee -a "$OUT/snap-summary.txt"
	if [ -s "$OUT/drm-state-$label.txt" ]; then
		grep -E 'mode: "[^"]+"' "$OUT/drm-state-$label.txt" |
			sed "s/^[[:space:]]*/[$label] drm /" | tee -a "$OUT/snap-summary.txt"
	fi
	SNAPS="$SNAPS $label"
}

