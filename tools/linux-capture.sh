# NAME BIDX OFF -> NAME BIDX OFF BYTEHEX BYTEDEC FLAG, byte = (base[bidx]+off)*4
resolve_regs() {
	reglist | awk -v bases="$DMU_BASES_STR" "$AWK_LIB"'
	BEGIN { nb = split(bases, B, " "); for (i = 1; i <= nb; i++) BV[i - 1] = hex2dec(B[i]) }
	/^#/ || NF < 3 { next }
	{
		flag = (NF >= 4) ? $4 : "-"
		if (!(($2 + 0) in BV) || BV[$2 + 0] < 0) { print $1, $2, $3, "-", -1, "NOBASE"; next }
		b = (BV[$2 + 0] + hex2dec($3)) * 4
		print $1, $2, $3, "0x" hex8(b), sprintf("%.0f", b), flag
	}' > "$OUT/reglist-resolved.txt"
}

# One 4-byte aligned pread per register (amdgpu_regs rejects unaligned or
# non-multiple-of-4 accesses and only decodes byte offsets below 4 MiB).
# bar5 mode maps the MMIO BAR read-only and does 32-bit loads.
PYREAD='
import errno, mmap, os, struct, sys
src, lst, mode = sys.argv[1], sys.argv[2], sys.argv[3]
ports = os.environ.get("RDNA4_READ_DATA_PORTS") == "1"
fd = os.open(src, os.O_RDONLY)
mv, size = None, 0
if mode == "bar5":
    size = os.fstat(fd).st_size
    mv = memoryview(mmap.mmap(fd, size, mmap.MAP_SHARED, mmap.PROT_READ)).cast("I")
out = []
for line in open(lst):
    f = line.split()
    if len(f) < 6 or f[0].startswith("#"):
        continue
    name, bidx, off, byteh, byted, flag = f[:6]
    addr = int(byted)
    if flag == "NOBASE":
        val = "SKIP:nobase"
    elif flag == "P" and not ports:
        val = "SKIP:dataport"
    elif (mode == "debugfs" and addr >= (1 << 22)) or (mode == "bar5" and addr + 4 > size):
        val = "SKIP:range"
    else:
        try:
            if mv is not None:
                v = mv[addr // 4]
            else:
                b = os.pread(fd, 4, addr)
                if len(b) != 4:
                    raise OSError(errno.EIO, "short read")
                v = struct.unpack("<I", b)[0]
            val = "0x%08x" % v
        except OSError as e:
            val = "ERR:" + errno.errorcode.get(e.errno, str(e.errno))
    out.append("%s %s %s %s %s" % (name, bidx, off, byteh, val))
sys.stdout.write("".join(s + "\n" for s in out))
'

# Fallback without python3: one dd per register (a few seconds per snapshot).
read_regs_dd() {
	local src=$1 name bidx off byteh byted flag v
	while read -r name bidx off byteh byted flag; do
		case "$name" in ''|'#'*) continue ;; esac
		if [ "$flag" = NOBASE ]; then
			v=SKIP:nobase
		elif [ "$flag" = P ] && [ "${RDNA4_READ_DATA_PORTS:-0}" != 1 ]; then
			v=SKIP:dataport
		elif [ "$byted" -ge 4194304 ]; then
			v=SKIP:range
		else
			v=$(dd if="$src" bs=4 count=1 skip=$((byted / 4)) 2>/dev/null | od -An -tx4 | tr -d ' \n')
			if [ ${#v} -eq 8 ]; then v=0x$v; else v=ERR:read; fi
		fi
		echo "$name $bidx $off $byteh $v"
	done < "$2"
}

read_regs() {
	case "$READER" in
	debugfs-py) python3 -c "$PYREAD" "$REG_SRC" "$1" debugfs ;;
	bar5-py)    python3 -c "$PYREAD" "$REG_SRC" "$1" bar5 ;;
	debugfs-dd) read_regs_dd "$REG_SRC" "$1" ;;
	*) awk '!/^#/ && NF >= 6 {print $1, $2, $3, $4, "SKIP:noreader"}' "$1" ;;
	esac
}

probe_reader() {
	local p="$OUT/.probe"
	grep -E '^(OTG0_OTG_CONTROL|DMCUB_CNTL|DMCUB_SCRATCH0) ' "$OUT/reglist-resolved.txt" > "$p"
	PROBE_OUT=$(read_regs "$p" 2>&1)
	rm -f "$p"
	case "$PROBE_OUT" in ''|*ERR:*|*Error*|*Traceback*) return 1 ;; esac
	return 0
}

# debugfs amdgpu_regs (python pread, else dd), else BAR5 mmap (python).
choose_reader() {
	local want=${RDNA4_READER:-auto} c
	for c in debugfs-py debugfs-dd bar5-py; do
		case "$want:$c" in
		auto:*|debugfs:debugfs-*|dd:debugfs-dd|bar5:bar5-py) ;;
		*) continue ;;
		esac
		case "$c" in
		debugfs-py) REG_SRC="$DRI/amdgpu_regs"; [ "$HAVE_PY" = 1 ] || continue ;;
		debugfs-dd) REG_SRC="$DRI/amdgpu_regs" ;;
		bar5-py)    REG_SRC="$CARD_DIR/device/resource5"; [ "$HAVE_PY" = 1 ] || continue ;;
		esac
		[ -e "$REG_SRC" ] || continue
		READER=$c
		if probe_reader; then
			say "register reader: $READER ($REG_SRC)"
			say "  probe: $(echo "$PROBE_OUT" | awk '{printf "%s=%s  ", $1, $5}')"
			case "$PROBE_OUT" in
			*0xffffffff*0xffffffff*0xffffffff*) say "!! probe reads all-ones: GPU asleep/off the bus?" ;;
			esac
			return 0
		fi
		say "!! reader $c failed: $(echo "$PROBE_OUT" | head -3 | tr '\n' ' ')"
	done
	READER=none REG_SRC=""
	return 1
}

