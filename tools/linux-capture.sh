# Plain regular files only, up to <instance>/<attr>.
copy_tree() {
	local s=$1 d=$2 f rel
	find -L "$s" -maxdepth 2 -type f 2>/dev/null | while IFS= read -r f; do
		rel=${f#"$s"/}
		mkdir -p "$d/$(dirname "$rel")"
		cat "$f" > "$d/$rel" 2>/dev/null
	done
}

# ip_discovery/die/0 holds one dir per hw_id (numeric) plus name symlinks
# (DMU -> 271, MP0, MP1, NBIF, GC, ...). Copy named IPs under their name and
# numeric dirs only when no name points at them.
collect_ipd() {
	local src="$CARD_DIR/device/ip_discovery/die/0" dst="$OUT/ip_discovery" e n refs=" " ip inst
	if [ ! -d "$src" ]; then
		say "!! no $src (kernel < 5.18 or discovery sysfs disabled)"
		return 1
	fi
	mkdir -p "$dst"
	for e in "$src"/*; do
		[ -L "$e" ] && refs="$refs$(basename "$(readlink "$e")") "
	done
	for e in "$src"/*; do
		n=${e##*/}
		[ -d "$e" ] || continue
		if [ ! -L "$e" ]; then
			case "$refs" in *" $n "*) continue ;; esac
		fi
		copy_tree "$e" "$dst/$n"
	done
	for ip in "$dst"/*; do
		for inst in "$ip"/*; do
			[ -f "$inst/base_addr" ] || continue
			printf '%-8s inst %s  v%s.%s.%s  base_addr: %s\n' "${ip##*/}" "${inst##*/}" \
				"$(cat "$inst/major" 2>/dev/null)" "$(cat "$inst/minor" 2>/dev/null)" \
				"$(cat "$inst/revision" 2>/dev/null)" "$(tr '\n' ' ' < "$inst/base_addr")"
		done
	done > "$dst/summary.txt"
	grep -E '^(DMU|MP0|MP1|NBIF|GC) ' "$dst/summary.txt" | sed 's/^/  /' | tee -a "$OUT/capture.log"
}

