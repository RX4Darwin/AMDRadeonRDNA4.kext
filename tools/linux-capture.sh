bundle() {
	local tarball="$OUT_BASE/$NAME.tar.gz" ntfs
	rm -f "$OUT/.probe"
	if [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ]; then
		chown -R "$SUDO_USER": "$OUT" 2>/dev/null
	fi
	if ! tar czf "$tarball" -C "$OUT_BASE" "$NAME" 2>> "$OUT/capture.log"; then
		say "!! tar failed — send the directory $OUT instead"
		return 1
	fi
	[ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ] && chown "$SUDO_USER": "$tarball" 2>/dev/null
	tarball=$(cd "$(dirname "$tarball")" && pwd)/${tarball##*/}
	hdr "done"
	echo "capture:  $tarball  ($(du -h "$tarball" | cut -f1))"
	echo
	printf '%s\n' "Copy it to Windows and put it in C:\\Users\\miguer\\Documents\\tools\\RDNA4FB\\captures\\"
	echo "  USB stick:  cp '$tarball' /media/\$USER/<stick>/"
	echo "  or the Windows partition (Windows Fast Startup / hibernation must be OFF):"
	ntfs=$(lsblk -rpno NAME,FSTYPE,SIZE,LABEL 2>/dev/null | awk '$2 == "ntfs" {printf "    %s  %s  %s\n", $1, $3, $4}')
	[ -n "$ntfs" ] && { echo "  NTFS partitions here:"; echo "$ntfs"; }
	echo "    sudo mkdir -p /mnt/win && sudo mount -t ntfs3 /dev/<partition> /mnt/win   # or -t ntfs-3g"
	echo "    sudo mkdir -p /mnt/win/Users/miguer/Documents/tools/RDNA4FB/captures"
	echo "    sudo cp '$tarball' /mnt/win/Users/miguer/Documents/tools/RDNA4FB/captures/ && sudo umount /mnt/win"
}

finish() {
	[ "$FINISHED" = 1 ] && return 0
	FINISHED=1
	trace_stop
	[ -d "$OUT" ] || return 0
	mark end
	hdr "wrap-up"
	collect_late
	decode_trace
	make_diffs
	{
		echo
		echo "DMUB trace: $TRACE_STATUS"
		[ -s "$OUT/dmub-decoded.txt" ] && grep -E '^# [0-9]+ commands|^non-mainline|^unknown command' "$OUT/dmub-decoded.txt"
		echo
		echo "Verdict lines to look for:"
		echo "  snap-summary.txt: boot/1080p60 should show an OTG 'on active=1920x1080"
		echo "                    total=2200x1125' (CEA timing) => register addresses are right"
		echo "  dmub-decoded.txt: VBIOS/* commands inside the 1080p75/720p60/replug windows"
		echo "                    are the mode-set recipe; 'NOT A MAINLINE VBIOS SUBTYPE' ="
		echo "                    GOP firmware dialect (compare with macOS rdna4-dmubhist)"
		echo "  diff-*.txt:       registers that change between modes = fallback recipe"
		echo "  firmware.txt:     DMCUB version (vs macOS rdna4-dmubver)"
	} | tee -a "$OUT/capture.log"
	bundle
}

on_signal() {
	say ""
	say "interrupted — stopping the trace and bundling what was captured"
	finish
	exit 130
}

