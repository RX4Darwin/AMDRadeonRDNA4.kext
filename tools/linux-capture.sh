# awk helpers (POSIX/mawk-safe: no strtonum/and/rshift, no printf %x on
# values >= 2^31)
# ---------------------------------------------------------------------------
AWK_LIB='
function hex2dec(h,   i, n, d) {
	h = tolower(h); sub(/^0x/, "", h); n = 0
	for (i = 1; i <= length(h); i++) {
		d = index("0123456789abcdef", substr(h, i, 1)) - 1
		if (d < 0) return -1
		n = n * 16 + d
	}
	return n
}
function hex8(n,   s, i) {
	s = ""
	for (i = 0; i < 8; i++) { s = substr("0123456789abcdef", n % 16 + 1, 1) s; n = int(n / 16) }
	return s
}
function hex2(n) { return substr(hex8(n), 7, 2) }
function bits(v, lo, w) { if (v < 0) return 0; return int(v / (2 ^ lo)) % (2 ^ w) }
function byte(v, k) { return bits(v, 8 * k, 8) }
function xor32(a, b,   r, p, i) {
	r = 0; p = 1
	for (i = 0; i < 32; i++) { if ((a % 2) != (b % 2)) r += p; a = int(a / 2); b = int(b / 2); p *= 2 }
	return r
}
'

