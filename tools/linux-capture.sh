# GPU / debugfs discovery
# ---------------------------------------------------------------------------
# Navi 48 = 0x7550 (preferred), 0x7551/0x7590 accepted, else first amdgpu card.
find_card() {
	local c n vend dev drv first="" pick=""
	if [ -n "${RDNA4_CARD:-}" ]; then
		pick="$SYSFS/class/drm/$RDNA4_CARD"
	else
		for c in "$SYSFS"/class/drm/card*; do
			n=${c##*/}
			case "$n" in *-*) continue ;; esac   # connectors (card1-HDMI-A-1)
			[ -r "$c/device/vendor" ] || continue
			vend=$(cat "$c/device/vendor" 2>/dev/null)
			[ "$vend" = 0x1002 ] || continue
			drv=$(readlink -f "$c/device/driver" 2>/dev/null)
			[ "${drv##*/}" = amdgpu ] || continue
			dev=$(tr 'A-F' 'a-f' < "$c/device/device" 2>/dev/null)
			[ -n "$first" ] || first=$c
			case "$dev" in
			0x7550) pick=$c; break ;;
			0x7551|0x7590) [ -n "$pick" ] || pick=$c ;;
			esac
		done
		[ -n "$pick" ] || pick=$first
	fi
	[ -n "$pick" ] && [ -d "$pick" ] || return 1
	CARD_DIR=$pick
	CARD=${pick##*/}
	BDF=$(readlink -f "$pick/device")
	BDF=${BDF##*/}
	PCI_ID="$(cat "$pick/device/vendor" 2>/dev/null):$(cat "$pick/device/device" 2>/dev/null)"
}

# /sys/kernel/debug/dri/<minor or BDF>/ whose `name` mentions our BDF.
find_dri() {
	local d minor=${CARD#card}
	if [ -n "${RDNA4_DEBUGFS_DIR:-}" ]; then DRI=$RDNA4_DEBUGFS_DIR; return 0; fi
	if [ ! -d "$DEBUGFS/dri" ] && [ "$DEBUGFS" = /sys/kernel/debug ] &&
	   ! mountpoint -q /sys/kernel/debug 2>/dev/null; then
		say "debugfs not mounted — mounting it at /sys/kernel/debug"
		mount -t debugfs none /sys/kernel/debug 2>/dev/null || say "!! mount -t debugfs failed"
	fi
	for d in "$DEBUGFS"/dri/*; do
		[ -e "$d/amdgpu_regs" ] && grep -qsF "$BDF" "$d/name" && { DRI=$d; return 0; }
	done
	for d in "$DEBUGFS/dri/$BDF" "$DEBUGFS/dri/$minor"; do
		[ -e "$d/amdgpu_regs" ] && { DRI=$d; return 0; }
	done
	for d in "$DEBUGFS"/dri/*; do
		grep -qsF "$BDF" "$d/name" && { DRI=$d; return 0; }
	done
	return 1
}

# DMU (DCN) segment bases from IP discovery: one hex dword base per line,
# line k = base_idx k (DMU_HWID = 271; "DMU" is a symlink to it).
dmu_bases() {
	local f d="$CARD_DIR/device/ip_discovery/die/0"
	if [ -n "${RDNA4_DMU_BASES:-}" ]; then
		DMU_BASES_STR=$RDNA4_DMU_BASES; DMU_BASES_SRC="env RDNA4_DMU_BASES"; return 0
	fi
	for f in "$d/DMU/0/base_addr" "$d/271/0/base_addr"; do
		[ -r "$f" ] || continue
		DMU_BASES_STR=$(tr -s ' \t\r\n' '    ' < "$f" | sed 's/^ *//; s/ *$//')
		[ -n "$DMU_BASES_STR" ] && { DMU_BASES_SRC=$f; return 0; }
	done
	# Values seen on this card (seg2 = 0x34C0 matches RDNA4FB/cursor-test.py).
	DMU_BASES_STR="0x00000012 0x000000C0 0x000034C0 0x00009000 0x02403C00"
	DMU_BASES_SRC="built-in default — ip_discovery not found, VERIFY"
	return 1
}

