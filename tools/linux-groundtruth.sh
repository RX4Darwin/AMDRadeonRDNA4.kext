# Page-table walk for each enabled VMID 1-15 (read-only, VRAM through debugfs).
WALK='
import os, struct, sys
regs, vram = sys.argv[1], sys.argv[2]
R = {}
for line in open(regs):
    f = line.split()
    if len(f) >= 5 and f[4].startswith("0x"):
        R[f[0]] = int(f[4], 16)
try:
    fd = os.open(vram, os.O_RDONLY)
except OSError as e:
    print("cannot open", vram, e)
    sys.exit(0)
def rd(addr):
    try:
        b = os.pread(fd, 4096, addr)
    except OSError:
        return None
    return struct.unpack("<512Q", b) if len(b) == 4096 else None
def bits(e):
    return ("valid %d system %d snooped %d exe %d read %d write %d frag %d mtype %d bit63 %d" %
            (e & 1, (e >> 1) & 1, (e >> 2) & 1, (e >> 4) & 1, (e >> 5) & 1, (e >> 6) & 1,
             (e >> 7) & 0x1f, (e >> 54) & 3, (e >> 63) & 1))
for vmid in range(1, 16):
    cntl = R.get("GCVM_CONTEXT%d_CNTL" % vmid)
    lo = R.get("GCVM_CONTEXT%d_PAGE_TABLE_BASE_ADDR_LO32" % vmid)
    hi = R.get("GCVM_CONTEXT%d_PAGE_TABLE_BASE_ADDR_HI32" % vmid)
    if cntl is None or lo is None or hi is None:
        continue
    base = (hi << 32) | lo
    depth = (cntl >> 1) & 3
    print("VMID %d: CNTL 0x%08x (enable %d, depth %d, block %d) BASE 0x%016x" %
          (vmid, cntl, cntl & 1, depth, (cntl >> 4) & 0xf, base))
    if not (cntl & 1) or not (base & 1):
        continue
    shown = [0]
    def walk(addr, level, path):
        t = rd(addr)
        if t is None:
            print("   read of VRAM 0x%x failed" % addr)
            return
        for i, e in enumerate(t):
            if shown[0] >= 6:
                return
            if not (e & 1):
                continue
            leaf = level == depth
            huge = (not leaf) and ((e >> 63) & 1) == 1
            tag = "PTE" if leaf else ("PDE-as-PTE" if huge else "PDE")
            print("   %-10s L%d[%3d] = 0x%016x  %s  path %s" % (tag, level, i, e, bits(e), path + "/%d" % i))
            if leaf or huge:
                shown[0] += 1
            else:
                walk(e & 0x0000fffffffff000, level + 1, path + "/%d" % i)
    walk(base & 0x0000fffffffff000, 0, "")
'
if [ -e "$DRI/amdgpu_vram" ] && [ -s "$OUT/gc-regs.txt" ]; then
	python3 -c "$WALK" "$OUT/gc-regs.txt" "$DRI/amdgpu_vram" > "$OUT/vm-walk.txt" 2>&1
else
