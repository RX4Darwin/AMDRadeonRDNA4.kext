#!/bin/bash
#
# linux-groundtruth.sh: READ-ONLY capture of what Linux amdgpu programs on this
# RX 9070 XT (gfx1201 / GC 12.0.1 / DCN 4.0.1), to compare with RDNA4FB.
# Written 2026-09-29 for the round-5 root-cause work (see
# docs/linux-ground-truth.md). It never writes a register or VRAM.
#
#   sudo bash tools/linux-groundtruth.sh idle      # desktop idle, mouse pointer visible
#   sudo bash tools/linux-groundtruth.sh vkcube    # run while vkcube (or any 3D app) is on screen
#   sudo bash tools/linux-groundtruth.sh compute   # optional: while a ROCm/OpenCL app runs
#
# Output: rdna4-groundtruth-<label>-<time>/ and a .tar.gz next to it.
# Needs: root, debugfs (mounted automatically if missing), python3.
# Captures:
#   gc-regs.txt    GC registers: VM contexts 0-15, GC hub/L2, RLC SRM/CSIB,
#                  clock gating, CP gfx ring/HQD/RS64, a few context registers
#   dcn-regs.txt   DCN pipe-0 registers: HUBP0/HUBPREQ0/CURSOR0, DPP0
#                  (DPP_TOP/CNVC/CM_CUR0/DSCL0/CM0), OTG0 CRC
#   vm-walk.txt    for each enabled VMID 1-15: the page-table walk from the
#                  context base through VRAM (debugfs amdgpu_vram), printing the
#                  raw PDE/PTE words of the first valid leaves (bit 63 = IS_PTE)
#   pm.txt         gpu_metrics, pp_dpm_sclk/mclk, power, amdgpu_pm_info (CG flags)
#   system.txt     kernel, amdgpu_firmware_info, ip_discovery bases, dmesg | amdgpu
# The register lists are generated from Linux master
# asic_reg/gc/gc_12_0_0_offset.h and asic_reg/dcn/dcn_4_1_0_offset.h
# ("NAME BASE_IDX DWORD_OFF"); do not hand-edit them.
set -u
LABEL=${1:-idle}
[ "$(id -u)" = 0 ] || { echo "run as root: sudo bash $0 $LABEL"; exit 1; }
command -v python3 >/dev/null || { echo "python3 is required"; exit 1; }
[ -d /sys/kernel/debug/dri ] || mount -t debugfs none /sys/kernel/debug 2>/dev/null
OUT="rdna4-groundtruth-$LABEL-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$OUT"

# The AMD card (vendor 0x1002) and its debugfs directory.
CARD=""
for c in /sys/class/drm/card[0-9]*; do
	case "$c" in *-*) continue ;; esac
	[ -e "$c/device/vendor" ] && [ "$(cat "$c/device/vendor")" = "0x1002" ] && { CARD=$c; break; }
done
[ -n "$CARD" ] || { echo "no AMD card found in /sys/class/drm"; exit 1; }
BDF=$(basename "$(readlink -f "$CARD/device")")
DRI=""
for d in /sys/kernel/debug/dri/*; do
	[ -e "$d/amdgpu_regs" ] || continue
	if grep -qs "$BDF" "$d/name"; then DRI=$d; break; fi
	[ -z "$DRI" ] && DRI=$d
done
[ -n "$DRI" ] || { echo "no debugfs amdgpu_regs (debugfs not mounted, or kernel lockdown: disable Secure Boot)"; exit 1; }
echo "card $CARD ($BDF), debugfs $DRI -> $OUT"

# IP-discovery segment bases: GC is hw id 11, DMU (DCN) is 271.
bases() {
	local d="$CARD/device/ip_discovery/die/0" f
	for f in "$d/$1/0/base_addr" "$d/$2/0/base_addr"; do
		[ -r "$f" ] && { tr -s ' \t\r\n' '    ' < "$f"; return 0; }
	done
	return 1
}
GC_BASES=$(bases GC 11) || GC_BASES=""
DMU_BASES=$(bases DMU 271) || DMU_BASES=""
[ -n "$GC_BASES" ] || echo "!! GC bases not found in ip_discovery; gc-regs.txt will be empty"
[ -n "$DMU_BASES" ] || echo "!! DMU bases not found in ip_discovery; dcn-regs.txt will be empty"

READER='
import os, struct, sys
src, bases, lst = sys.argv[1], sys.argv[2].split(), sys.argv[3]
B = [int(x, 16) for x in bases]
fd = os.open(src, os.O_RDONLY)
print("# NAME BASE_IDX DWORD_OFF BYTE_ADDR VALUE   (bases: %s)" % " ".join(bases))
for line in open(lst):
    f = line.split()
    if len(f) < 3 or f[0].startswith("#"):
        continue
    name, idx, off = f[0], int(f[1]), int(f[2], 16)
    if idx >= len(B):
        print(name, idx, hex(off), "-", "SKIP:nobase")
        continue
    addr = (B[idx] + off) * 4
    try:
        b = os.pread(fd, 4, addr)
        v = ("0x%08x" % struct.unpack("<I", b)[0]) if len(b) == 4 else "ERR:short"
    except OSError as e:
        v = "ERR:%d" % e.errno
    print(name, idx, hex(off), "0x%x" % addr, v)
'

